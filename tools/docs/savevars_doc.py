"""Generate reference/save-variables.md from runtime/save_vars_S02-S05.txt (output of savevars.py)."""
import os as _os
_REPO = _os.path.abspath(_os.path.join(_os.path.dirname(__file__), '..', '..'))
_RESEARCH = _os.environ.get('SLY2_RESEARCH', _os.path.join(_REPO, '..', 'research'))

import re, os, collections
R = _RESEARCH
OUT = os.path.join(_REPO, 'docs', 'reference', 'save-variables.md')
GS = 0x3D4A60
rows = []
for line in open(f'{R}/runtime/save_vars_S02-S05.txt'):
    m = re.match(r'^(\S+)\s+kind=\s*(-?\d+) x3=\s*(\d+) ib=0x([0-9a-f]+)\s+(.*)$', line)
    if m: rows.append((m[1], int(m[2]), int(m[3]), int(m[4], 16), m[5].split()))
KIND = {0: 'int', 2: 'oid', 3: 'float', 4: 'bool', 9: 'id?'}
def val(v, k):
    if k == 3:
        import struct
        return ' / '.join(f"{struct.unpack('<f', struct.pack('<I', int(x, 16)))[0]:.1f}" for x in v)
    return ' / '.join(v) if len(set(v)) > 1 else v[0]
L = ['# Save variables', '',
 'All persistent progress lives in the 0x5400-byte blob `g_gs` = **0x3D4A60**; a schema loaded from every world file names each variable',
 '(see [save-memcard](../engine/save-memcard.md)). This page was generated by `tools/savevars_doc.py` from a runtime decode of the schema',
 '(`runtime/scripts/savevars.py` on save states S02-S05, Paris hub) and is therefore `[C:runtime]` for names, offsets, kinds and the values shown.',
 '**Address = 0x3D4A60 + offset.** Kinds: int, float, bool (packed bits; `x3` = bit count for arrays), oid. `x3` > 0 on non-bool kinds = array length.',
 'v2 notes: later rounds (S06-S62) confirmed `bentley.hpCur` (+0x68, max 40) and `murray.hpCur` (+0x80, max 60), `powerUps.mppukfAcquired` (+0x98, bit n = gadget n), `<char>.apukCur[3]` = gadget slots, `episodeCurrent`/`episodeBest`, `widCurrent` = level index, and the `m<N>_*` / `t<N>_*` records = JOBs / TASKs (`is_complete` = 1 at task state 2) `[C:runtime]`; see [game-progression](../engine/game-progression.md).',
 f'Totals: {len(rows)} named variables, 960 symbols, 5,461 trie entries.', '',
 '## 1. Top-level variables', '', '| Variable | Offset | Address | Kind | x3 | Value S02 / S03 / S04 / S05 | Notes |', '|---|---|---|---|---|---|---|']
NOTES = {'loot.ccoin': 'coins at 0x3D4B00 (HUD via SW+0x3B20; live write of 777 shown on the HUD [C:live]); 6 -> 9 when 3 coins were collected', 'oidPoCurrent': 'current playable character (JT oid 7)',
 'sly.hpCur': 'Sly health; JT+0xE00 points here; max 40 at JT+0xDFC', 'dt': 'total play time (s); SW+0x3B1C key',
 'loot.mplootkc': 'loot count per kind k; pickpocket key 0x45A+k -> [k]; [4] (g_gs+0xB4) went 0 -> 1 between S02 and S03',
 'powerUps.mppukfAcquired': 'acquired power-ups (43 bits); builtins 138/139', 'suck_history.mission_0': 'difficulty sample 0 of 3 ("suck" = Sly 1 difficulty term)',
 'flags.lang': 'option key k0', 'flags.fNoVibration': 'option key k7 (rumble gate)', 'episodeCurrent': '', 'widCurrent': ''}
top = [r for r in rows if not re.match(r'^(episode\.|m\d+_|t\d+_)', r[0])]
for n, k, x3, ib, v in top:
    L.append(f"| `{n}` | 0x{ib:04X} | 0x{GS+ib:06X} | {KIND.get(k, k)} | {x3} | {val(v, k)} | {NOTES.get(n, '')} |")
L += ['', 'Option keys k0..k10 precomputed at SW+0x3B2C: `flags.lang`, `nMixerMode`, `uMusicVolume`, `uEffectsVolume`, `fUseHeadset`, `dxScreenCenter`,',
      '`dyScreenCenter`, `fNoVibration`, `fReverseLookAround`, `fReverseAim`, `fAutosaveWarned` (ResetGs keeps these 11).', '',
      '## 2. Per-episode and per-level variables', '',
      'Pattern (9 episodes = worlds intro..blimp): `episode.<world>.dt` (play time; SW+0x3B58[w]), `episode.<world>.percent_complete` (SW+0x3B7C[w]),',
      'and per level `episode.<world>.level.<level>.afClue` (32 packed bools, one per clue bottle), `.fVault` (safe opened), `.booty.aoidAssembly[15]` (some levels).', '',
      '| World | Levels (in schema order) | percent_complete offset | Values seen |', '|---|---|---|---|']
eps = collections.OrderedDict()
for n, k, x3, ib, v in rows:
    m = re.match(r'^episode\.([a-z_]+)\.(.*)$', n)
    if not m: continue
    e = eps.setdefault(m[1], {'levels': [], 'pc': None, 'notes': []})
    lm = re.match(r'^level\.([a-z_0-9]+)\.', m[2])
    if lm and lm[1] not in e['levels']: e['levels'].append(lm[1])
    if m[2] == 'percent_complete': e['pc'] = (ib, v)
    if len(set(v)) > 1 or (v[0] != '0x0' and m[2] not in ('dt',)):
        e['notes'].append(f"`{m[2]}` 0x{GS+ib:06X} = {val(v, k)}")
for w, e in eps.items():
    pc = f"0x{GS+e['pc'][0]:06X}" if e['pc'] else ''
    L.append(f"| {w} | {', '.join(e['levels'])} | {pc} | {'; '.join(e['notes'][:4])} |")
L += ['', 'Example: the clue bottle collected in S05 set bit 10 of `episode.nightclub.level.exterior.afClue` = 0x3D4CD8 (0 -> 0x400).', '',
      '## 3. Missions (`m<N>_<name>`: focus_count, is_complete, time_played, suck_value)', '',
      'Probably one per JOB (11 JOB objects live in the hub; the Paris episode has `m1_*`). `<N>` = episode 0..8. Offsets 0x0D9C.. (16 bytes each).', '']
ms = collections.OrderedDict()
for n, k, x3, ib, v in rows:
    m = re.match(r'^(m(\d+)_[a-z0-9_]+)\.', n)
    if m: ms.setdefault(m[2], [])
    if m and m[1] not in ms[m[2]]: ms[m[2]].append(m[1])
for e, names in ms.items():
    L.append(f"- **episode {e}**: " + ', '.join(f'`{x}`' for x in names))
L += ['', '## 4. Tasks (`t<N>_<name>`: focus_count, complete_count, is_complete, state, from_memcard)', '',
      'Probably one per TASK (99 TASK objects live in the Paris hub). `state` uses the TASK states (0 locked, 1 available, 3 done: all `t0_*` intro tasks',
      'are 3 in the save states). 20 bytes each from offset ~0x1284 up to 0x5094.', '']
ts = collections.OrderedDict()
for n, k, x3, ib, v in rows:
    m = re.match(r'^(t(\d+)_[a-z0-9_]+)\.', n)
    if m:
        ts.setdefault(m[2], [])
        if m[1] not in ts[m[2]]: ts[m[2]].append(m[1])
for e, names in ts.items():
    L.append(f"<details><summary>episode {e}: {len(names)} tasks</summary>\n\n" + ', '.join(f'`{x[len(e)+2:]}`' for x in names) + '\n\n</details>\n')
L += ['', '## 5. Earlier findings now named', '', '| Address | Earlier description | Variable |', '|---|---|---|',
 '| 0x3D4B00 | coins (FINDINGS.md) | `loot.ccoin` |', '| 0x3D4CD8 | clue bitmask afClue | `episode.nightclub.level.exterior.afClue` |',
 '| 0x3D4AB0 | health (open item) | `sly.hpCur` |', '| 0x3D4B14 | pickpocket loot | `loot.mplootkc[4]` |', '']
open(OUT, 'w').write('\n'.join(L))
print(len(rows), len(top))
