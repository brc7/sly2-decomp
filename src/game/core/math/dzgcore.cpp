/** @sly2-annot addr=0x11A770
 * Purpose: not written up yet; only the symbol name (pre-existing / Sly 1-derived) describes it.
 * Confidence: mid (draft) - evidence: pre-existing symbol name only; behaviour not reviewed
 * See: docs/reference/functions/core-library.md#dzgcore-0x11a550-0x11afe0
 * @end-sly2-annot */
// Makes constraint dz hold (Sly 1's EnforceDzgDz): adds it to the active set, re-decomposes the active system and
// moves constraints that would violate their bounds to the bound lists, repeating until consistent.
void EnforceDzgDz(DZG *dzg, DZ *dz)
{
    int iter;
    if (dz) {
        RemoveDlEntry(&dzg->dlD, dz);
        AppendDlEntry(&dzg->dlA, dz);
        dzg->cdzA++;
    }
    for (iter = 0; iter < 10; iter++) {
        DZ *pdzI, *pdzJ, *pdzK, *pdzBest;
        float *pg;
        int i, k;
        float gMin;

        float *pgMat = dzg->agMat;
        for (pdzI = (DZ *)dzg->dlA.head; pdzI; pdzI = (DZ *)pdzI->dle.next)
            for (pdzJ = (DZ *)dzg->dlA.head; pdzJ; pdzJ = (DZ *)pdzJ->dle.next)
                *pgMat++ = pdzI->ag[pdzJ - dzg->adz];
        CroutDecomp(dzg->cdzA, dzg->agMat, dzg->agLu);
        float *pgB = dzg->agB;
        for (pdzI = (DZ *)dzg->dlA.head; pdzI; pdzI = (DZ *)pdzI->dle.next)
            *pgB++ = -pdzI->g10;
        CroutSolve(dzg->cdzA, dzg->agLu, dzg->agB, dzg->agX);
        for (i = 0; i < dzg->cdz; i++) {
            float g = 0.0f;
            float *pgX = dzg->agX;
            for (pdzI = (DZ *)dzg->dlA.head; pdzI; pdzI = (DZ *)pdzI->dle.next)
                g += *pgX++ * pdzI->ag[i];
            dzg->adz[i].g14 = g;
        }

        pdzBest = 0;
        gMin = 1.0f;
        k = 0;
        pg = dzg->agX;
        for (pdzI = (DZ *)dzg->dlA.head; pdzI; pdzI = (DZ *)pdzI->dle.next) {
            float x = *pg++;
            if (x > 1e-4f) {
                // Empty asm, allocation-only operands (emits nothing): two extra uses of the +-1e-4 constants
                // raise their global-alloc priority above the hoisted D_002A4120/D_002A4124 loads, whose
                // REG_EQUIV-less pseudos otherwise win (local-alloc doubles the constants' live length), so
                // the constants get f5/f4 and the globals f7/f6 as in the target.
                __asm__("" : : "f"(1e-4f), "f"(-1e-4f));
                if (pdzI->gMax != D_002A4120) {
                    float t = (pdzI->gMax - pdzI->gC) / x;
                    if (t < gMin) {
                        gMin = t;
                        pdzBest = pdzI;
                        k = 4;
                    }
                }
            } else if (x < -1e-4f) {
                if (pdzI->gMin != D_002A4124) {
                    float t = (pdzI->gMin - pdzI->gC) / x;
                    if (t < gMin) {
                        gMin = t;
                        pdzBest = pdzI;
                        k = 2;
                    }
                }
            }
        }
        for (pdzK = (DZ *)dzg->dlB.head; pdzK; pdzK = (DZ *)pdzK->dle.next) {
            if (pdzK->g14 > -1e-4f) {} else {
                float t = -pdzK->g10 / pdzK->g14;
                if (t < gMin) {
                    gMin = t;
                    pdzBest = pdzK;
                    k = 1;
                }
            }
        }
        for (pdzK = (DZ *)dzg->dlC.head; pdzK; pdzK = (DZ *)pdzK->dle.next) {
            if (pdzK->g14 < 1e-4f) {} else {
                float t = -pdzK->g10 / pdzK->g14;
                if (t < gMin) {
                    gMin = t;
                    pdzBest = pdzK;
                    k = 3;
                }
            }
        }
        for (i = 0; i < dzg->cdz; i++) {
            DZ *pdzT = &dzg->adz[i];
            pdzT->g10 += gMin * pdzT->g14;
        }
        pg = dzg->agX;
        for (pdzI = (DZ *)dzg->dlA.head; pdzI; pdzI = (DZ *)pdzI->dle.next)
            pdzI->gC += gMin * *pg++;

        switch (k) {
        case 0:
            return;
        case 2:
            dzg->cdzA--;
            RemoveDlEntry(&dzg->dlA, pdzBest);
            AppendDlEntry(&dzg->dlB, pdzBest);
            if (pdzBest == dz)
                return;
            break;
        case 1:
            dzg->cdzA++;
            RemoveDlEntry(&dzg->dlB, pdzBest);
            AppendDlEntry(&dzg->dlA, pdzBest);
            break;
        case 4:
            dzg->cdzA--;
            RemoveDlEntry(&dzg->dlA, pdzBest);
            AppendDlEntry(&dzg->dlC, pdzBest);
            if (pdzBest == dz)
                return;
            break;
        case 3:
            dzg->cdzA++;
            RemoveDlEntry(&dzg->dlC, pdzBest);
            AppendDlEntry(&dzg->dlA, pdzBest);
            break;
        }
    }
}

static inline void InitDli(DLI *pdli, DL *pdl)
{
    pdli->pdl = pdl;
    pdli->ppv = (void **)pdl;
    pdli->ibDle = pdl->ibDle;
    pdli->pdliNext = g_pdliFirst;
    g_pdliFirst = pdli;
}

static inline void *PvNextDli(DLI *pdli)
{
    void *pv = *pdli->ppv;
    pdli->ppv = (void **)((char *)pv + pdli->ibDle);
    return pv;
}

/** @sly2-annot addr=0x11ABF8
 * Purpose: Moves equality constraints into the active list, EnforceDzgDz, then repeatedly adds the
 *   most-violated constraint
 * Info: proposed name SolveDzgFilled (T1); TU dzgcore
 * Notes: COLLISION: SolveDzg already used (existing symbol at 0x158988); renamed to SolveDzg_11ABF8 |
 *   superseded: SolveDzg_11ABF8 (arbitration) | arbitration other name: CONFIRMED static: Sly1 SolveDzg loop
 *   (equality rows Uncat->Pos, EnforceDzgDz(0), add most-violated row) WITHOUT the lazy FillDzgDz; only
 *   caller SolveInequalitie
 * Confidence: mid (draft) [T1 0.60] - evidence: Sly 1 / Lilly reference; arbitration; sources:
 *   r1_116918+arbitration
 * See: docs/engine/core-library.md#7-key-functions,
 *   docs/reference/functions/core-library.md#dzgcore-0x11a550-0x11afe0
 * @end-sly2-annot */
// Solves a filled DZG: moves equality constraints into the active list, enforces them, then repeatedly enforces
// the most violated remaining constraint until none is violated.
extern "C" void SolveDzgFilled(DZG *dzg)
{
    DLI dli;
    DZ *pdz;

    InitDli(&dli, &dzg->dlD);
    while ((pdz = (DZ *)PvNextDli(&dli)) != 0) {
        if (pdz->nKind == 1) {
            RemoveDlEntry(&dzg->dlD, pdz);
            AppendDlEntry(&dzg->dlA, pdz);
            dzg->cdzA++;
        }
    }
    EnforceDzgDz(dzg, 0);
    g_pdliFirst = dli.pdliNext;

    for (;;) {
        DZ *pdzMin = 0;
        float gMin = -0.01f;
        DZ *pdzT;
        for (pdzT = (DZ *)dzg->dlD.head; pdzT; pdzT = (DZ *)pdzT->dle.next) {
            if (pdzT->g10 < gMin) {
                gMin = pdzT->g10;
                pdzMin = pdzT;
            }
        }
        if (!pdzMin) {
            break;
        }
        EnforceDzgDz(dzg, pdzMin);
    }
}

