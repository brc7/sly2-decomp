    register qword r2 __asm__("vf1");
    register qword r0 __asm__("vf2");
    register qword r1 __asm__("vf3");
    r2 = pb->r[2];
    r0 = pb->r[0];
    ROW(r2, a0, a1, a2);
    r1 = pb->r[1];
