// Closes the stream: closes the host file, cancels a CD read in flight, then the base Close.
extern "C" void CStreamBis_Close(CBinaryInputStream *stream)
{
    int fd = stream->fd;
    if (fd >= 0) {
        sceClose(fd);
        stream->fd = -1;
    }
    if (stream->sector >= 0) {
        if (stream->readRequested != 0)
            sceCdBreak();
        stream->sector = -1;
    }
    CBinaryInputStream_Close(stream);
}

