// Reads a little-endian signed 16-bit value.
short CBinaryInputStream::S16Read()
{
    if (m_cb >= 2)
    {
        short v = m_pb[1] << 8;
        v |= m_pb[0];
        m_pb += 2;
        m_cb -= 2;
        return v;
    }

    short v;
    Read(sizeof(short), &v);
    return v;
}

// Reads a little-endian signed 32-bit value.
int CBinaryInputStream::S32Read()
{
    if (m_cb >= 4)
    {
        int v = m_pb[0] + (m_pb[1] << 8) + (m_pb[2] << 16) + (((char *)m_pb)[3] << 24);
        m_pb += 4;
        m_cb -= 4;
        return v;
    }

    int v;
    Read(sizeof(int), &v);
    return v;
}

