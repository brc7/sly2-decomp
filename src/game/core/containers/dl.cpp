/** @sly2-annot addr=0x11A118
 * Purpose: Unlink entry (linear search for predecessor) and fix up active iterators
 * Info: proposed name RemoveSlEntry (T1); TU dl
 * Confidence: mid (draft) [T1 0.70] - evidence: static analysis; sources: r1_116918
 * See: docs/reference/functions/core-library.md#dl-0x11a050-0x11a550
 * @end-sly2-annot */
extern "C" void RemoveSlEntry(SL *psl, void *pv)
{
    void **ppvNext = PPVNEXT(psl, pv);
    void **ppv = &psl->head;
    SLI *psli;
    while (pv != *ppv) {
        ppv = PPVNEXT(psl, *ppv);
    }
    for (psli = D_002DD2F8; psli; psli = psli->psliNext) {
        if (psli->ppv == ppvNext) {
            psli->ppv = ppv;
        }
    }
    *ppv = *ppvNext;
    if (psl->head == 0) {
        psl->tail = 0;
    } else if (*ppv == 0) {
        psl->tail = (char *)ppv - psl->ibSle;
    }
    *ppvNext = 0;
}

