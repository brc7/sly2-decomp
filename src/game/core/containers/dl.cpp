// Appends entry at the tail of a doubly linked list.
void AppendDlEntry(DL *list, void *entry)
{
    DLE *link = PDLE(list, entry);
    if (!list->tail) {
        list->tail = entry;
        list->head = entry;
    } else {
        DLE *lastLink = PDLE(list, list->tail);
        link->prev = list->tail;
        lastLink->next = entry;
        list->tail = entry;
    }
}

