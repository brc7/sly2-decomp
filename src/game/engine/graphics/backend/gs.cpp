// Returns ceil(log2(value)) (0 for 0 and 1, at most 31): used for texture width/height exponents.
// Also known as: NLog2 (upstream readable / Sly 1 name).
uint CeilLog2(uint value)
{
    uint log2 = 0;
    uint bit = 1;
    while (bit < value && log2 < 31)
    {
        bit <<= 1;
        log2++;
    }
    return log2;
}

