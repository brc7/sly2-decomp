// VBlank-start interrupt handler: wakes a thread waiting in SyncVBlank, then by display mode (D_002DEDBC) applies the
// field fix-up (modes 1, 2) or flips the display buffer itself (mode 3).
int VBlankS_Interrupt(int ch)
{
    if (D_002DFB58) {
        D_002DFB58 = 0;
        iSignalSema(D_002DFB4C);
    }
    switch (D_002DEDBC) {
    case 1:
        if (!D_002DFB5C) {
            D_002BE594 = D_002BE590;
            BlendDisplayOnBufferMismatch();
        }
        break;
    case 2:
        if (!D_002DFB5C)
            BlendDisplayOnBufferMismatch();
        break;
    case 3:
        D_002DEDB0++;
        D_002DFB60 = 1;
        sceGsPutDispEnv(&D_002DEB80[D_002DEDB0 & 1]);
        break;
    }
    asm volatile("sync\n\tei");
    return 0;
}

// Waits for the next vblank (blocks on the semaphore the vblank handler signals).
void SyncVBlank()
{
    D_002DFB58 = 1;
    func_00234A60(D_002DFB4C);
}

// FIELD bit of the GS CSR register (bitfield view).
static inline int ReadCsrFieldBit() { return ((CSR *)SLY2_HW_GS_CSR)->FIELD; }
// Presents the frame: waits for vblank, picks the field for the next frame, sets the draw environment's half-pixel
// offset for it, and swaps the double-buffered display/draw environments (sceGsSwapDBuff), under the GS critical
// section.
void SwapGsBuffers()
{
    D_002DFB5C = 1;
    SyncVBlank();
    D_002DFB5C = 0;
    D_002DEDB8 = D_002DEDB4;
    if (D_002BE594 > 0) {
        D_002DEDB4 = 0;
        D_002BE594--;
    } else {
        D_002DEDB4 = ReadCsrFieldBit() == 0;
    }
    EnterCritSect(&D_002DFB40);
    sceGsSetHalfOffset((D_002DEDB0 & 1) ? &D_002DEBE0 : &D_002DECD0, 0x800, 0x800, D_002DEDB4);
    func_00234CA0(0);
    D_002DEDB0++;
    sceGsSwapDBuff(D_002DEB80, D_002DEDB0);
    if (D_002DEDBC == 1 || D_002DEDBC == 2)
        BlendDisplayOnBufferMismatch();
    sceGsSyncPath(0, 0);
    LeaveCritSect(&D_002DFB40);
}

// Puts the draw environment back after a vblank-handler flip (display mode 3 drops to mode 2): re-reads the field and
// reapplies the half offset and draw environment.
void RestoreGsBuffers()
{
    if (D_002DEDBC == 3)
        D_002DEDBC = 2;
    if (D_002DFB60) {
        D_002DFB60 = 0;
        D_002DEDB4 = ReadCsrFieldBit() == 0;
        sceGsSetHalfOffset((D_002DEDB0 & 1) ? &D_002DECD0 : &D_002DEBE0, 0x800, 0x800, D_002DEDB4);
        func_00234CA0(0);
        sceGsPutDrawEnv((D_002DEDB0 & 1) ? &D_002DECC0 : &D_002DEBD0[0]);
    }
}

// Recovers the GS after a reset: clears both frame buffers, waits for vblank, resets the GS (sceGsResetGraph),
// re-derives the field and swaps buffers so drawing resumes cleanly (inferred from the body; the name is Sly 1's).
void GS_Interrupt(int ch)
{
    DRAWENV *pdraw;
    int field;
    int c;
    D_002DFB5C = 1;
    ClearFrameBuffers();
    SyncVBlank();
    D_002DFB5C = 0;
    sceGsResetGraph(0, 1, 2, 1);
    field = ((unsigned int)*(unsigned int *)SLY2_HW_GS_CSR >> 0xD) & 1;
    D_002DEDBC = 0;
    D_002BE594 = 0;
    D_002DEDB8 = field;
    D_002DEDB4 = field == 0;
    if (D_002DEDB0 & 1) {
        pdraw = &D_002DEBE0;
    } else {
        pdraw = &D_002DECD0;
    }
    sceGsSetHalfOffset(pdraw, 0x800, 0x800, (short)D_002DEDB4);
    FlushCache(0);
    c = D_002DEDB0 + 1;
    D_002DEDB0 = c;
    sceGsSwapDBuff(D_002DEB80, c);
}

// GS FINISH interrupt handler: when a SendDmaSyncGsFinish is waiting and the FINISH event fired, signals its
// semaphore.
int ResetGs()
{
    if (D_002DFB54 && (*(volatile long *)SLY2_HW_GS_CSR & 2)) {
        D_002DFB54 = 0;
        iSignalSema(D_002DFB50);
    }
    asm volatile("sync\n\tei");
    return -1;
}

// Sends a DMA chain to the given channel and blocks until the GS signals FINISH (enables the FINISH interrupt, sends,
// waits on the semaphore). Used for synchronous uploads such as textures at level load.
void SendDmaSyncGsFinish(sceDmaChan *pch, QW *pqw)
{
    EnterCritSect(&D_002DFB40);
    D_002DFB54 = 1;
    *(volatile long *)SLY2_HW_GS_CSR |= 2;
    sceGsPutIMR(sceGsGetIMR() & ~0x200);
    func_00234CA0(0);
    sceDmaSend(pch, pqw);
    func_00234A60(D_002DFB50);
    LeaveCritSect(&D_002DFB40);
}

// Builds the static GIF packet that clears a frame: a flat sprite in the given colour (blended when alpha < 0x80)
// drawn as 32-pixel-wide strips over the 512-line screen, with the depth test set by n (1: colour only, 2: colour and
// depth, 3: depth only).
void BuildClearGifs(QW *aqw, RGBA rgba, int n)
{
    GIFS gifs;
    gifs.AllocStatic(0x25, aqw);
    gifs.AddPrimPack(rgba.alpha < 0x80 ? 0x46 : 6, 1, 0xE);
    gifs.PackAD(1, (ulong)rgba.red | ((ulong)rgba.green << 8) | ((ulong)rgba.blue << 16) | ((ulong)rgba.alpha << 24));
    ulong test;
    switch (n) {
    case 1: test = 0x31001; break;
    case 2: test = 0x32001; break;
    case 3: test = 0x30000; break;
    }
    gifs.PackAD(0x47, test);
    gifs.PackAD(0x42, 0x44);
    for (int x = 0; x < 0x200; x += 0x20) {
        gifs.PackAD(5, (ulong)((0x700 + x) * 16) | ((ulong)0x790 << 20));
        gifs.PackAD(5, (ulong)((0x720 + x) * 16) | ((ulong)0x870 << 20));
    }
    gifs.PackAD(0x47, 0x70000);
    gifs.AddPrimEnd();
}

