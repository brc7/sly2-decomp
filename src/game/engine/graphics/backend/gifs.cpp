// Writes UV as one 64-bit REGLIST word.
void GIFS::ListUV(int u, int v)
{
    CheckReg(0, 3);
    ulong *pul = (ulong *)m_pb;
    m_pb = (uchar *)(pul + 1);
    *pul = u | (v << 16);
}

// Writes XYZ2 as one 64-bit REGLIST word.
void GIFS::ListXYZ(int x, int y, int z)
{
    CheckReg(0, 5);
    ulong *pul = (ulong *)m_pb;
    m_pb = (uchar *)(pul + 1);
    *pul = (x | (y << 16)) | ((ulong)z << 32);
}

// Writes XYZF2 as one 64-bit REGLIST word.
void GIFS::ListXYZF(int x, int y, int z, int fog)
{
    CheckReg(0, 4);
    ulong *pul = (ulong *)m_pb;
    m_pb = (uchar *)(pul + 1);
    *pul = (x | (y << 16)) | ((ulong)(z & 0xFFFFFF) << 32) | ((ulong)fog << 56);
}

