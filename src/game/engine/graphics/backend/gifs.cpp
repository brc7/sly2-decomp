// Opens a REGLIST primitive with creg registers per loop; NLOOP is counted from the List* calls and stored by EndPrim.
void GIFS::AddPrimList(int creg, ulong regs)
{
    EndPrim(0);
    QW *pqw = (QW *)m_pb;
    m_pb = (uchar *)(pqw + 1);
    pqw->aul[1] = regs;
    pqw->aul[0] = ((ulong)creg << 60) | (1L << 58);
    m_creg = creg;
    m_pqwPrim = pqw;
    m_cregAll = 0;
}

// Writes RGBAQ as one 64-bit REGLIST word (colour and Q).
void GIFS::ListRGBAQ(uint rgba, float q)
{
    CheckReg(0, 1);
    ulong *pul = (ulong *)m_pb;
    m_pb = (uchar *)(pul + 1);
    *pul = (ulong)rgba | ((ulong)*(uint *)&q << 32);
}

