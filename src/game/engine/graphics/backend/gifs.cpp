// Writes an A+D register write in PACKED format: data d to GS register address a.
void GIFS::PackAD(long a, long d)
{
    CheckReg(1, 14);
    QW *pqw = (QW *)m_pb;
    m_pb = (uchar *)(pqw + 1);
    pqw->aul[0] = d;
    pqw->aul[1] = a;
}

