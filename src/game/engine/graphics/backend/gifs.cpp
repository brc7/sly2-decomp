// Adds an IMAGE-mode GIF tag for cqw quadwords of image data (texture/CLUT upload through the GIF) that the caller
// appends.
void GIFS::AddImage(int cqw)
{
    EndPrim(0);
    QW *pqw = (QW *)m_pb;
    m_pb = (uchar *)(pqw + 1);
    pqw->aul[0] = cqw | (2L << 58);
    pqw->aul[1] = 0;
}
