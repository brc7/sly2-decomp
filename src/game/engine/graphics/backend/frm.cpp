/* The list iterator as this TU spells it (sly2/dli.h DLI with a constructor and destructor). */
extern void *D_002DD2FC;
struct DLI {
    DL *list;
    void **next;
    int linkOffset;
    void *previous;
    DLI(DL *owner)
    {
        int offset = owner->linkOffset;
        previous = D_002DD2FC;
        D_002DD2FC = this;
        list = owner;
        next = (void **)owner;
        linkOffset = offset;
    }
    ~DLI() { D_002DD2FC = previous; }
    void *Next()
    {
        void *value = *next;
        next = (void **)((unsigned int)value + linkOffset);
        return value;
    }
};

