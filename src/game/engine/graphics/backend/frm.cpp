// Drains the render thread (wait/signal sema twice), optionally re-renders the last frame 3 times to both buffers and
// clears pending frames.
void FlushFrames(int fReset)
{
    unsigned int i;
    for (i = 0; i < 2; i++)
        func_00234A60(D_002DEB1C);
    for (i = 0; i < 2; i++)
        func_00234A40(D_002DEB1C);
    while (!D_002DEB20)
        ;
    if (fReset && D_002DEB14) {
        for (int j = 0; j < 3; j++) {
            RenderFrame(D_002DEB14, 1);
            if (D_002DEB14->n30 & 1)
                BlendPrevFrame();
            SwapGsBuffers();
        }
        D_002DEDBC = 3;
    }
    if (fReset) {
        FRM *pfr = D_002DEA50;
        do {
            ClearPendingFrame(pfr);
            pfr++;
        } while (pfr < D_002DEA50 + 2);
    }
    ClearPhase(3);
    D_002DEB14 = 0;
}

static inline ulong Tex0FromDisp(ulong disp)
{
    return ((disp & 0x1FF) << 5) | (((disp >> 16) & 0x3F) << 14) | (((disp >> 24) & 0x3F) << 20);
}
// Draws the other (previous) framebuffer back over the current one as 32-px textured strips with alpha 0x64/0x80
// (motion-blur/frame blend), unless disabled by D_002DEB24/D_003E12C8.
void BlendPrevFrame()
{
    if (D_002DEB24 || g_sw.fUnk3e38)
        return;
    GIFS gifs;
    QW aqw[0x64];
    gifs.AllocStatic(0x64, aqw);
    gifs.AddDmaCnt();
    gifs.AddPrimPack(0, 1, 0xE);
    gifs.PackAD(0x3F, 0);
    ulong *pdisp = (ulong *)((D_002DEDB0 & 1) ? D_002DEBE0 : D_002DECD0);
    gifs.PackAD(6, Tex0FromDisp(*pdisp) | 0x2A8000000L);
    gifs.PackAD(0x14, 0x61);
    gifs.PackAD(8, 5);
    gifs.PackAD(0x47, 0x33001);
    gifs.PackAD(0x42, 0x3000000064L);
    gifs.PackAD(1, 0x3F80000080808080L);
    gifs.PackAD(0x40, 0xDE000101FF0000L);
    gifs.AddPrimPack(0x156, 2, 0x43);
    int v = (D_002DEDB8 & 1) ? 0 : 0x10;
    for (int x = 0; x < 0x200; x += 0x20) {
        gifs.PackUV((x << 4) | 8, v);
        gifs.PackXYZF((x + 0x700) << 4, 0x7900, 0, 0);
        gifs.PackUV(((x + 0x20) << 4) | 8, v + 0xE00);
        gifs.PackXYZF((x + 0x720) << 4, 0x8700, 0, 0);
    }
    gifs.AddPrimPack(0, 1, 0xE);
    gifs.PackAD(0x40, 0xDF000001FF0000L);
    gifs.PackAD(0x61, 0);
    gifs.AddPrimEnd();
    gifs.AddDmaEnd();
    gifs.EndDmaCnt();
    SendDmaSyncGsFinish(D_002DE598, aqw);
}


