/* One render-list entry: kind (pass bucket), sort depth, two DMA CALL addresses (0 = none). */

typedef struct MATRIX4V { float mat[4][4]; } __attribute__((aligned(16))) MATRIX4V;
struct V3 { float x, y, z; };
struct V4 { V3 v; float w; };

/* Views of objects whose classes are not modelled yet; only the fields this TU reads. */
struct CM { char pad[0x4C]; float rNear; float rFar; char pad2[0xC]; MATRIX4V cameraMatrix; char pad3[0xA0]; MATRIX4V viewProj; };
struct FR { char pad[0x24]; uchar *chainStart; };   /* the frame: where its VIF1 chain starts */
/* SW: vecLightRgb (+0x3E28), the stereo flag (+0x3E38, sw.h's fUnk3e38: also keys shd.cpp's colour correction),
   a forced clear (+0x3E3C) and a background-image rebuild request (+0x3EA8) (inferred from these uses) */
struct GAME { char pad[0x3E28]; int vecLightRgb[4]; int isStereo; int forceClear; char pad2[0x3EA8 - 0x3E40]; int rebuildBackground; };
typedef void (*PFNRP)(VIFS *, int, int);
#define NUM_RPL_KINDS 26
#define DMA_TAG_CALL 0x50000000    /* DMAtag id CALL (5 << 28); the address goes in the upper word */

extern GAME D_003DD490;
extern VIFS D_002DEA28;
extern FR *g_pfrmOpen;
extern FR D_002DEA50;
extern char D_002DF800[], D_002DF940[], D_002DFA80[], D_002DEDC0[], D_002DF010[];
extern DMAS D_002DEA00;
extern CM D_002DDF40;
extern V3 D_002C1F00, D_002C1F10;
extern RPL D_003B3980[];
extern RPL *D_003D4A50;
int D_002DE5A4;   /* draw's .bss */
/* The render pass of each draw kind (26 kinds), index into the pass hook table D_002BDD88 (draw's .data). */
int D_002BDD20[NUM_RPL_KINDS] = {4, 3, 0, 0, 11, 0, 11, 6, 7, 1, 0, 0, 2, 0, 0, 8, 0, 1, 9, 0, 1, 5, 10, 0, 1, 0};
/* Pass table: begin and end hook per pass. Declared as an array of pairs, not of a {pfnBegin, pfnEnd} struct:
   g++ folds a struct member's +4 into the hoisted table base, the C original materialised D_002BDD88+4 apart. */
extern PFNRP D_002BDD88[][2];

extern "C" {
void qsort(void *, int, int, int (*)(const void *, const void *));
void BuildStereoEyeViewProj(CM *pcm, int k, int n, MATRIX4V *pm0, MATRIX4V *pm1);
void BeginRpGlob(VIFS *pvifs, void *a1, void *a2);
void BuildWorldBackgroundImage(GAME *pgame, int n);
}

typedef int (*PFNCMP)(const void *, const void *);

// qsort comparator for RPL pointers: descending depth (farthest first, back-to-front for blended passes), ties broken
// by entry address. Used for kinds 1, 2, 5, 6, 10 and 25.
int CompareRplFarToNear(RPL **entryA, RPL **entryB)
{
    RPL *lhs = *entryA;
    RPL *rhs = *entryB;
    if (rhs->depth < lhs->depth)
        return -1;
    if (lhs->depth < rhs->depth)
        return 1;
    return lhs - rhs;
}

// qsort comparator for RPL pointers: ascending depth (nearest first), ties broken by reverse entry address. Used for
// kind 21 only.
int CompareRplNearToFar(RPL **entryA, RPL **entryB)
{
    RPL *lhs = *entryA;
    RPL *rhs = *entryB;
    if (rhs->depth < lhs->depth)
        return 1;
    if (lhs->depth < rhs->depth)
        return -1;
    return rhs - lhs;
}

// Counting-sorts the frame's RPL array by kind (26 kinds) into the pointer array aprpl, recording each kind's first
// index (aiFirst) and end index (ac), then depth-sorts the blended kinds. Returns the total entry count (end of kind
// 25).
int CprplPartitionArpl(int count, RPL *entries, RPL **sorted, int *firstIndex, int *endIndex)
{
    int nextIndex[NUM_RPL_KINDS];
    int i;
    for (i = NUM_RPL_KINDS - 1; i >= 0; i--)
        endIndex[i] = 0;
    for (int j = 0; j < count; j++)
        endIndex[entries[j].kind]++;
    firstIndex[0] = 0;
    nextIndex[0] = 0;
    for (i = 1; i < NUM_RPL_KINDS; i++) {
        int t;
        firstIndex[i] = t = endIndex[i - 1];
        endIndex[i] += t;
        nextIndex[i] = firstIndex[i];
    }
    for (int k = 0; k < count; k++, entries++)
        sorted[nextIndex[entries->kind]++] = entries;
    qsort(sorted + firstIndex[5], endIndex[5] - firstIndex[5], 4, (PFNCMP)CompareRplFarToNear);
    qsort(sorted + firstIndex[6], endIndex[6] - firstIndex[6], 4, (PFNCMP)CompareRplFarToNear);
    qsort(sorted + firstIndex[10], endIndex[10] - firstIndex[10], 4, (PFNCMP)CompareRplFarToNear);
    qsort(sorted + firstIndex[1], endIndex[1] - firstIndex[1], 4, (PFNCMP)CompareRplFarToNear);
    qsort(sorted + firstIndex[2], endIndex[2] - firstIndex[2], 4, (PFNCMP)CompareRplFarToNear);
    qsort(sorted + firstIndex[25], endIndex[25] - firstIndex[25], 4, (PFNCMP)CompareRplFarToNear);
    qsort(sorted + firstIndex[21], endIndex[21] - firstIndex[21], 4, (PFNCMP)CompareRplNearToFar);
    return endIndex[25];
}

// Pass 10 begin (kind 22): re-CALL frame context (or stereo eye), DIRECT Z-only clear D_002DF010, re-upload
// camera/ambient VU globals, BASE/OFFSET 0x32/0x1E7, then BeginRpGlob. (inferred)
extern "C" void BeginRpForeground(VIFS *vifs, void *a1, void *a2)
{
    V4 clipConstants[2];
    MATRIX4V viewProj, cameraMatrix;
    if (D_003DD490.isStereo) {
        if (g_pfrmOpen == &D_002DEA50)
            vifs->AddDmaCall((QW *)D_002DF940);
        else
            vifs->AddDmaCall((QW *)D_002DFA80);
    } else {
        vifs->AddDmaCall((QW *)D_002DF800);
    }
    vifs->m_fCheckCnt = 1;
    vifs->AddDmaCnt();
    vifs->AddVifFlush();
    vifs->AddVifDirect(0x25, (QW *)D_002DF010, 0);
    vifs->AddVifBaseOffset(0, 0);
    {
        CM *camera = &D_002DDF40;
        float rNear = camera->rNear;
        float rFar = camera->rFar;
        float depthRatio = (rNear + rFar) / (rNear - rFar);
        float depthScale = rNear * (1.0f - depthRatio);
        clipConstants[0].v = D_002C1F00;
        clipConstants[0].w = 1.0f / depthScale;
        clipConstants[1].v = D_002C1F10;
        clipConstants[1].w = -depthRatio / depthScale;
        vifs->AddVifUnpack(UPK_V4_32, 2, clipConstants, 0);
        if (D_003DD490.isStereo) {
            if (g_pfrmOpen == &D_002DEA50)
                BuildStereoEyeViewProj(camera, 1, 0, &viewProj, &cameraMatrix);
            else
                BuildStereoEyeViewProj(camera, 2, 0, &viewProj, &cameraMatrix);
        } else {
            MATRIX4V *pm1 = &camera->viewProj;
            MATRIX4V *pm2 = &camera->cameraMatrix;
            viewProj = *pm1;
            cameraMatrix = *pm2;
        }
    }
    vifs->AddVifUnpack(UPK_V4_32, 4, &viewProj, 2);
    vifs->AddVifUnpack(UPK_V4_32, 4, &cameraMatrix, 6);
    vifs->AddVifUnpack(UPK_V4_32, 1, (char *)&g_sw.vecLightRgb, 10);
    vifs->AddVifBaseOffset(0x32, 0x1E7);
    vifs->EndDmaCnt();
    BeginRpGlob(vifs, a1, a2);
}

// g_pfrmOpen: Sly 1 name of the current-frame pointer (frm.cpp defines it; config/symbol_addrs.txt names 0x2DEA4C so).
// Builds the frame VIF1 chain: partitions RPLs, emits frame/camera VU constants, then for each RPL kind-change calls
// the pass table begin/end hooks D_002BDD88[D_002BDD20[kind]] and emits the RPL DMA CALL tags; flushes VIFS/GIFS.
// (inferred)
extern "C" void DrawSw(GAME *world)
{
    MATRIX4V mat0;
    MATRIX4V mat1;
    RPL *sorted[0x2000];
    int firstIndex[NUM_RPL_KINDS];
    int endIndex[NUM_RPL_KINDS];
    V4 v0, v1;
    int count;
    int passPrev, kindPrev;
    int i;

    count = CprplPartitionArpl(D_003D4A50 - D_003B3980, D_003B3980, sorted, firstIndex, endIndex);
    {
        uchar *writePointer = D_002DEA28.m_pb;
        g_pfrmOpen->chainStart = writePointer;
    }
    D_002DEA28.AddDmaCall((QW *)D_002DF800);
    D_002DEA28.m_fCheckCnt = 1;
    D_002DEA28.AddDmaCnt();
    if (world->forceClear || firstIndex[1] == endIndex[1])
        D_002DEA28.AddVifDirect(0x25, (QW *)D_002DEDC0, 0);
    if (D_003DD490.isStereo) {
        D_002DEA28.AddVifFlush();
        if (g_pfrmOpen == &D_002DEA50)
            D_002DEA28.AddDmaCall((QW *)D_002DF940);
        else
            D_002DEA28.AddDmaCall((QW *)D_002DFA80);
    }
    D_002DEA28.AddVifBaseOffset(0, 0);
    {
        float sNear = D_002DDF40.rNear;
        float sFar = D_002DDF40.rFar;
        float depthRatio = (sNear + sFar) / (sNear - sFar);
        float depthScale = sNear * (1.0f - depthRatio);
        v0.v = D_002C1F00;
        v0.w = 1.0f / depthScale;
        v1.v = D_002C1F10;
        v1.w = -depthRatio / depthScale;
    }
    D_002DEA28.AddVifUnpack(UPK_V4_32, 2, &v0, 0);
    D_002DEA28.AddVifUnpack(UPK_S32, 1, &D_002DE5A4, 0xD);
    D_002DE5A4 = 0;
    if (D_003DD490.isStereo) {
        if (g_pfrmOpen == &D_002DEA50)
            BuildStereoEyeViewProj(&D_002DDF40, 1, 0, &mat0, &mat1);
        else
            BuildStereoEyeViewProj(&D_002DDF40, 2, 0, &mat0, &mat1);
    } else {
        MATRIX4V *pm0 = &D_002DDF40.viewProj;
        MATRIX4V *pm1 = &D_002DDF40.cameraMatrix;
        mat0 = *pm0;
        mat1 = *pm1;
    }
    D_002DEA28.AddVifUnpack(UPK_V4_32, 4, &mat0, 2);
    D_002DEA28.AddVifUnpack(UPK_V4_32, 4, &mat1, 6);
    D_002DEA28.AddVifUnpack(UPK_V4_32, 1, world->vecLightRgb, 0xA);
    D_002DEA28.AddVifBaseOffset(0x32, 0x1E7);
    D_002DEA28.EndDmaCnt();
    passPrev = -1;
    kindPrev = -1;
    for (i = 0; i < count; i++) {
        RPL *entry = sorted[i];
        int kind = entry->kind;
        int pass = D_002BDD20[kind];
        if (pass != passPrev) {
            if (passPrev != -1)
                D_002BDD88[passPrev][1](&D_002DEA28, kindPrev, kind);
            D_002BDD88[pass][0](&D_002DEA28, kind, kindPrev);
            kindPrev = kind;
            passPrev = pass;
        }
        if (entry->pbCall) {
            *(ulong *)D_002DEA28.m_pb = ((ulong)(unsigned int)entry->pbCall << 32) | DMA_TAG_CALL;
            D_002DEA28.m_pb += sizeof(QW);
        }
        if (entry->pvCall) {
            *(ulong *)D_002DEA28.m_pb = ((ulong)(unsigned int)entry->pvCall << 32) | DMA_TAG_CALL;
            D_002DEA28.m_pb += sizeof(QW);
        }
    }
    if (passPrev != -1)
        D_002BDD88[passPrev][1](&D_002DEA28, kindPrev, -1);
    D_003D4A50 = 0;
    D_002DEA00.Flush();
    D_002DEA28.Flush();
    if (world->rebuildBackground) {
        world->rebuildBackground = 0;
        BuildWorldBackgroundImage(world, 0);
    }
}

