/* Rebases the shared (kind 1) colour tables and bitmaps by ib, colour-correcting each table entry. */
extern "C" void RelocateSharedColorTables(int ib)
{
    int iclut;
    CLUT *pclut;
    SHDRGBA *prgba;
    int cbmp;
    BMP *pbmp;
    iclut = 0;
    if (D_003DCFF8 > 0) {
        do {
            pclut = &D_003DCFFC[iclut];
            if (pclut->kind == 1) {
                pclut->argba = (SHDRGBA *)(ib + (unsigned int)pclut->argba);
                prgba = pclut->argba;
                if (prgba < prgba + pclut->ccolor) {
                    do {
                        ColorCorrectRgba(prgba);
                        prgba++;
                    } while (prgba < pclut->argba + pclut->ccolor);
                }
            }
            iclut += 1;
        } while (iclut < D_003DCFF8);
    }
    if (D_003DCFF0 > 0) {
        cbmp = D_003DCFF0;
        pbmp = D_003DCFF4;
        do {
            cbmp -= 1;
            if (pbmp->kind == 1) {
                pbmp->pv = (void *)(ib + (int)pbmp->pv);
            }
            pbmp++;
        } while (cbmp != 0);
    }
}

// Texture passes for a shader kind: shdk 1 -> 2, shdk 7 -> 3 (2 if flag 0x20), else 1. (inferred)
extern "C" int GetShaderPassCount(SHD *pshd)
{
    switch (pshd->shdk) {
    case 1:
        return 2;
    case 7:
        if (!(pshd->grfshd & 0x20)) return 3;
        return 2;
    }
    return 1;
}

// TEX0 register value for frame i / pass j of a texture: base bitmap TEX0 | clut TEX0. (inferred)
extern "C" ulong Tex0FromTexIframeCtk(TEX *ptex, int iframe, int ipass)
{
    ulong fl = ptex->apbmp[iframe]->tex0.word;
    CLUT *pclut = ptex->apclut[iframe * GetShaderPassCount(ptex->pshd) + ipass];
    if (pclut)
        fl |= pclut->tex2.word;
    return fl;
}

