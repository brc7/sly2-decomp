// SCROLLER vt8 Update. (inferred)
// Also known as: UpdateScroller (upstream readable / Sly 1 name; UpdateScroller__FP8SCROLLERf).
void SCROLLER::Update()
{
    SCROLLER *p = this;
    float uOffset, vOffset;
    if (IsSlEmpty(&p->instances)) return;
    uOffset = fmodf(p->uOffset * (1.0f / 4096.0f) + p->uSpeed * p->uSpeedScale * g_clock.deltaTime, p->uRange);
    vOffset = fmodf(p->vOffset * (1.0f / 4096.0f) + p->vSpeed * p->vSpeedScale * g_clock.deltaTime, p->vRange);
    SetSaiDuDv(p, uOffset, vOffset);
}

float GetScrollerCompletion(SCROLLER *pscroller) __asm__("GetScrollerCompletion__FP8SCROLLER");
// Completion fraction of a SCROLLER: the average of its u and v offsets as fractions of their wrap ranges (0.5 for an
// axis that does not move).
// Also known as: UCompleteScroller (upstream readable / Sly 1 name).
float GetScrollerCompletion(SCROLLER *pscroller)
{
    float uComp = 0.0f;
    if (pscroller->uSpeed != 0.0f)
        uComp = ((pscroller->uOffset * (1.0f / 4096.0f)) / pscroller->uRange) * 0.5f;
    else
        uComp = 0.5f;
    if (pscroller->vSpeed != 0.0f)
        uComp += ((pscroller->vOffset * (1.0f / 4096.0f)) / pscroller->vRange) * 0.5f;
    else
        uComp += 0.5f;
    return uComp;
}

