// EYES vt7 Init. (inferred)
// Also known as: InitEyes (upstream readable / Sly 1 name; InitEyes__FP4EYESP4SAAF).
extern "C" void InitEyes(EYES *eyes, SAAF *psaaf)
{
    InitSaa(eyes, psaaf);
    eyes->unknown60=psaaf->cLoopWord;
    eyes->blinkTime=psaaf->ag[0];
    { float a=psaaf->ag[1]; float b=psaaf->ag[2]; eyes->openTimeMin=a; eyes->openTimeMax=b; }
    eyes->doubleBlinkChance=psaaf->ag[3];
    eyes->eyess=EYESS_Nil;
    SetEyesEyess(eyes,EYESS_Open);
}

// Sets the blink state of an EYES animation (open, closing, closed, opening) and starts its timing: on opening, picks
// how long the eyes stay open (zero for a double blink, chance uDoubleBlink) and the frame rate of the blink.
void SetEyesEyess(EYES *peyes, EYESS eyess)
{
    if (eyess == peyes->eyess)
        return;
    switch (eyess)
    {
    case EYESS_Open:
        peyes->frameRate = (peyes->numFrames * 2) * (1.0f - peyes->openFraction) / peyes->blinkTime;
        peyes->frame = (peyes->numFrames - 1) * peyes->openFraction;
        if (RandomFloatInRange__Fff(0.0f, 1.0f) < peyes->doubleBlinkChance)
            peyes->openTime = 0.0f;
        else
            peyes->openTime = RandomFloatInRange__Fff(peyes->openTimeMin, peyes->openTimeMax);
        break;
    case EYESS_Closing:
        break;
    case EYESS_Closed:
        if ((int)peyes->frame != peyes->numFrames - 1)
            peyes->frame = peyes->numFrames - 1;
        break;
    }
    peyes->eyess = eyess;
    peyes->stateTime = g_clock.time;
}

// EYES vt8 Update. (inferred)
// Also known as: UpdateEyes (upstream readable / Sly 1 name; UpdateEyes__FP4EYESf).
void EYES::Update()
{
    EYES *peyes = this;
    if (IsSlEmpty(&peyes->instances) || peyes->numFrames < 2)
        return;
    EYESS eyessNext = peyes->eyess;
    switch (peyes->eyess)
    {
    case EYESS_Open:
        if (g_clock.time - peyes->stateTime >= peyes->openTime)
            eyessNext = EYESS_Closing;
        break;
    case EYESS_Closing:
    {
        float frameRate = peyes->frameRate * g_clock.deltaTime;
        peyes->frame += frameRate;
        if (peyes->frame >= (float)peyes->numFrames)
        {
            peyes->frame -= frameRate;
            eyessNext = ((int)peyes->frame == peyes->numFrames - 1) ? EYESS_Closed : EYESS_Opening;
        }
        break;
    }
    case EYESS_Closed:
        if (peyes->openFraction < 1.0f)
            eyessNext = EYESS_Opening;
        break;
    case EYESS_Opening:
        peyes->frame -= peyes->frameRate * g_clock.deltaTime;
        if (peyes->frame <= peyes->numFrames * peyes->openFraction)
            eyessNext = EYESS_Open;
        break;
    }
    SetEyesEyess(peyes, eyessNext);
    SetSaiIframe(peyes, (int)peyes->frame);
}

// Set EYES closed amount (called per EYES SAA by SetSoEyesClosed 0x1F80D0) (inferred)
// Also known as: SetEyesClosed (upstream readable / Sly 1 name; SetEyesClosed__FP4EYESf).
extern "C" void SetEyesClosed(EYES *eyes, float g)
{
    eyes->openFraction = g;
    if (g >= 1.0f) {
        SetEyesEyess(eyes, EYESS_Closed);
    } else {
        eyes->eyess = EYESS_Nil;
        SetEyesEyess(eyes, EYESS_Open);
    }
    SetSaiIframe(eyes, (int)eyes->frame);
}

