// Projects a world point into the path basis and returns path direction. (inferred)
void ProjectPointOntoTnPath(TN *p,qword v,qword *out,qword *normal) {
    U pos;
    M3 m;
    if(p->path) {
        EvaluateShapeAtDistance(p->path,p->progress,&pos.q,normal);
        m=BuildOrthonormalMatrixZ(*normal,D_002A2DC0q);
        *out=InverseRotate(m,VuSub(v,pos.q));
    } else if(p->fCircle) {
        U a;
        a.q=SetVectorCylind(p->progress/p->radius,p->radius,0.0f);
        pos.q=VuAdd(*(qword *)&p->centerPosition,a.q);
        *normal=Normalize(CrossTied(D_002A2DC0q,a.q));
        m=BuildOrthonormalMatrixZ(*normal,D_002A2DC0q);
        *out=InverseRotate(m,VuSub(v,pos.q));
    } else {
        *normal=Normalize(GetLoWorldMatrix(p)->r[0]);
        *out=ConvertPosBetweenLos(0,p,v);
    }
}

static inline qword Rotate(const M3 &m,qword v) {
    __asm__("vmulax.xyz ACC,%1,%0x\n\tvmadday.xyz ACC,%2,%0y\n\tvmaddz.xyz %0,%3,%0z" : "+j"(v) : "j"(m.r[0]),"j"(m.r[1]),"j"(m.r[2])); return v;
}
// Evaluates a clamped path offset (fmodf), rotates/translates to world. (inferred)
void EvaluateTnPathPos(TN *p,float *times,COEF *coef,BOUND *bounds,int mode,qword *out,float time,float delta) {
    U pos,normal,center;
    M3 m;
    U rotated;
    float *f=pos.f;
    int i;
    i=2; do {
        float t=*times;
        float x=coef->a+t*(coef->b+t*coef->c);
        float lo=bounds->low,hi=bounds->high;
        if(x<lo) x=lo;
        else if(hi<x) x=hi;
        *f++=x; times++; bounds++; coef++;
    } while(--i>=0);
    if(mode==2) pos.f[0]=-pos.f[0];
    if(p->fCylind) pos.q=SetVectorCylind(pos.f[0],pos.f[1],pos.f[2]);
    if(p->path) {
        EvaluateShapeAtDistance(p->path,mode!=1?time-delta:time+delta,&center.q,&normal.q);
        m=BuildOrthonormalMatrixZ(normal.q,D_002A2DC0q);
        rotated.q=Rotate(m,pos.q);
    } else if(p->fCircle) {
        float period=p->radius*6.2831855f;
        float phase=mode!=1?time-delta:time+delta;
        float angle=fmodf(phase,period);
        center.q=SetVectorCylind(angle/p->radius,p->radius,0.0f);
        qword arc=center.q;
        center.q=VuAdd(arc,*(qword *)&p->centerPosition);
        normal.q=Normalize(CrossEarly(D_002A2DC0q,arc));
        m=BuildOrthonormalMatrixZ(normal.q,D_002A2DC0q);
        rotated.q=Rotate(m,pos.q);
    } else {
        center.i[0]=center.i[1]=center.i[2]=0;
        pos.f[0]+=delta;
        rotated.q=ConvertPosBetweenLos(p,0,pos.q);
    }
    *out=VuAdd(center.q,rotated.q);
}

