    __asm__("vmulax.xyzw $ACC, %1, %2x\n\tvmaddx.xyzw %0, %3, %4x" : "=j"(r) : "j"(*(qword *)&pa->basePosition), "j"(b), "j"(*(qword *)&pa->adjustedPosition), "j"(a));
