/** @sly2-annot addr=0x1BC2F8
 * Purpose: Classify polygon (too few points / convex CW / CCW / not convex) from turn signs
 * Info: proposed name ClassifyCid14Polygon (T2); class CID14; TU tu_1BC050
 * Confidence: low (draft) [T2 0.40] - evidence: static analysis; sources: r5b_rest+verdicts_B
 * See: docs/engine/physics-collision.md#7-key-functions,
 *   docs/reference/functions/physics-collision.md#tu_1bc050-0x1bc050-0x1be398
 * @end-sly2-annot */
// Classifies the outline from its turn signs: too few points, convex clockwise, convex counter-clockwise, or not
// convex.
int ClassifyCid14Polygon(CID14V *polygon)
{
    int cFlip, i, sPrev, sgn;
    M4 m;
    if (polygon->numPoints < 2)
        return 2;
    cFlip = 0;
    i = 0;
    sPrev = 0;
    m = *GetMat(polygon);
    sgn = ComparePosXY(MulPt(&m, polygon->points[0]), MulPt(&m, polygon->points[1]));
    for (; i < polygon->numPoints - 1; i++) {
        int i0 = WrapCid14PointIndex(polygon, i);
        int i1 = WrapCid14PointIndex(polygon, i0 + 1);
        int i2 = WrapCid14PointIndex(polygon, i1 + 1);
        qword c = MulPt(&m, polygon->points[i2]);
        qword b = MulPt(&m, polygon->points[i1]);
        qword a = MulPt(&m, polygon->points[i0]);
        int s = ComparePosXY(b, c);
        int t;
        if (s) {
            if (s == -sgn)
                cFlip++;
        }
        sgn = s;
        t = GetTurnSignXY(a, b, c);
        if (t) {
            if (t == -sPrev)
                return 0;
            sPrev = t;
        }
    }
    if (cFlip >= 3)
        return sPrev == 0;
    switch (sPrev) {
    case -1:
        return 4;
    case 1:
        return 3;
    }
    return 2;
}

