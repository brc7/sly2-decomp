/* A contact (XP) as far as this TU reads it: two 0x40-byte sides (the object at +0x08 and the contact position at
   +0x10 of each), the contact normal, friction, kind, the contact's index in its group (+0xA8) and the relative
   velocity. */
struct XPS
{
    void *pv0;              /* +0x00 */
    void *pv4;              /* +0x04 */
    SO *pso;                /* +0x08 */
    void *pvC;              /* +0x0C */
    qword qwPos;            /* +0x10 */
    char pad20[0x20];
};
struct XP
{
    XPS axps[2];
    qword qwNormal;         /* +0x80 */
    int pad90;
    float gFriction;        /* +0x94 friction coefficient (HYPOTHESIS: scales the friction rows' limits) */
    int pad98;
    int nKind;              /* +0x9C 14: the limit comes from the first side's gravity and mass */
    int padA0[2];
    int ixp;                /* +0xA8 index in the group (DZGXP::apxp) */
    XP *pxpNext;            /* +0xAC */
    qword qwVRel;           /* +0xB0 */
};

