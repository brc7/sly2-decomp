// Launches pso from the launcher: aims at the target point (optionally advanced by a predicted travel time and
// offset along the aim direction), then by the object's class gives it a speed vector (0x52), a velocity toward the
// point at its own launch speed with a matching orientation (0x51), or a ballistic velocity, adds a random spin,
// and tells class 0x50 objects their target. Runtime: Bentley's darts are launched through it.
extern "C" void LaunchSoFromLauncher(LAUNCH *plaunch, SOV *pso)
{
    MATRIX4V matParent;
    qwordV posStart = GetLoWorldPos(pso);
    VV posOrigin(posStart);
    SOV *psoSource = plaunch->psoSource;
    XFV *pxf;
    if (psoSource)
        pxf = psoSource->GetLocalTransform(&matParent);
    else {
        pxf = &D_002C44F0;
        LoadIdentity(&matParent);
    }
    qwordV dpos;
    float dist;
    {
        MATRIX4V mat;
        __ml__FRC7MATRIX4T0(&mat, &pxf->matWorld, &matParent);
        dpos = VuSub(Point(mat, plaunch->posTarget), posStart);
        dist = QwordX(Length(dpos));
        float t = Clamp(GFromClq(plaunch->clqPredict, dist), plaunch->lmPredict.gMin, plaunch->lmPredict.gMax);
        if (t != 0.0f) {
            MATRIX4V matPredict;
            LoadIdentityMatrix4(pxf, 0, &mat, 0, t);
            __ml__FRC7MATRIX4T0(&matPredict, &mat, &matParent);
            dpos = VuSub(Point(matPredict, plaunch->posTarget), posStart);
        }
    }
    dist = QwordX(Length(dpos));
    float offset = Clamp(GFromClq(plaunch->clqOffset, dist), plaunch->lmOffset.gMin, plaunch->lmOffset.gMax);
    qwordV posAim;
    qwordV posLaunch = AddScaled(posOrigin, VU_FLOAT(offset), Normalize(dpos));
    posAim = QwFromVf(posLaunch);
    if (IsBasicDerivedFrom__FP5BASIC3CID(pso, 0x4F)) {
        SetBombOwner(pso, plaunch);
        RefreshSwObjectCollisionFilter(D_003DD490, pso);
    }
    pso->Add();
    SetSoCnstrForce(pso, 0);
    SetSoCnstrTorque(pso, 0);
    SetLoParent(pso, 0, 3);
    if (IsBasicDerivedFrom__FP5BASIC3CID(pso, 0x52)) {
        SetSoPosXfVelocityLocal(pso, VECTORV(pso->svLaunch, 0.0f, 0.0f).q);
    } else if (IsBasicDerivedFrom__FP5BASIC3CID(pso, 0x51)) {
        qwordV v = VuFloatFromWord(pso->svLaunch) * Normalize2(posAim, posStart);
        pso->SetVelocity(v);
        MATRIX3V mat;
        LoadLookAtMatrix(&mat, v);
        pso->RotateToMat(&mat);
    } else {
        qwordV vAccel = GetSoGravity(pso);
        qwordV v = CalculateBallisticLaunchVelocity(plaunch->pitch, posStart, posLaunch, vAccel);
        pso->SetVelocity(v);
    }
    if (plaunch->lmSpin.gMax > 0.0f) {
        float g = RandomFloatInRange(plaunch->lmSpin);
        float x = RandomFloatInRange__Fff(-1.0f, 1.0f);
        float y = RandomFloatInRange__Fff(-1.0f, 1.0f);
        float z = RandomFloatInRange__Fff(-1.0f, 1.0f);
        qwordV w = NormalizeTo(QwToVf(VECTORV(x, y, z).q)) * VU_FLOAT(g);
        pso->SetAngularVelocity(w);
    }
    if (IsBasicDerivedFrom__FP5BASIC3CID(pso, 0x50))
        pso->SetTarget(plaunch->psoSource, VECTOR4V(plaunch->posTarget));
}
