void BuildContactGroup(SW *pv, SO *px, int *pc, SO **apx)
{
    TL *pn;
    px->grf |= 0x8000000;
    apx[*pc] = px;
    (*pc)++;
    for (pn = px->ptree->ptlFirst; pn; pn = pn->ptlNext) {
        SO *q;
        SOPHYS *pe;
        if (!pn->pxp) continue;
        q = pn->pso;
        if (q->grf & 0x8000000) continue;
        pe = q->psophys;
        if (!pe) continue;
        if (pe->constrPos.k == 3 && pe->constrRot.k == 3) continue;
        BuildContactGroup(pv, q, pc, apx);
    }
}

