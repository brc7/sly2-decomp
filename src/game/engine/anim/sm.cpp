{
    SM *psm = (SM *)this;
    PostLoLoad(psm);
    if (psm->psminit) {
        LO *plo = FindSwObject(&D_003DD490, 4, psm->psminit->oidRoot, psm);
        ApplySmToObject(psm, (ALO *)plo, psm->psminit->oidInitialState, psm->psminit->grfapl);
    }
}

