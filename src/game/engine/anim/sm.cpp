extern "C" void RetractSma(SMA *p)
{
    if (!IsSmaRetracted(p)) {
        void *pv = p->pasegaCur;
        if (pv) {
            p->pasegaCur = 0;
            RetractAsega(pv);
        }
        RemoveDlEntry__FP2DLPv(&p->stateMachine->dlSma, p);
        RemoveDlEntry__FP2DLPv(&g_sw.dlSma, p);
        p->HandleSpliceEvent(3, 0, 0, 0, 0);
        p->Release();
    }
}
