// Loads a state machine from the level stream: its states (each with an OID), its transitions (from/to state, the
// animation segment that plays the transition, flags and weight), the precomputed state-to-state hop-count table per
// transition mask, and the optional initial activation.
void SM::LoadFromBrx(CBinaryInputStream *pbis)
{
    int i = 0;
    int j;
    int cstep;
    int fChanged;
    LO *plo;
    InitDl(&dlSma, 0x14);
    STACKSCOPE stackscope;
    CLoadCollectorArray collector;
    LoadSwObjectsFromBrx(parent, pbis, &collector);
    for (i = 0; i < collector.m_cplo; i++)
    {
        plo = collector.m_aplo[i];
        plo->Remove();
    }
    csms = pbis->U8Read();
    asms = (SMS *)AllocWorldHeapBlock(csms * sizeof(SMS), 16);
    for (i = 0; i < csms; i++)
    {
        SMS *psms = &asms[i];
        psms->oid = (OID)pbis->S32Read();
        psms->oidNext = (OID)pbis->S32Read();
    }
    for (i = 0; i < csms; i++)
    {
        SMS *psms = &asms[i];
        switch (psms->oidNext)
        {
        case OID_Nil:
            psms->ismsNext = -1;
            break;
        case 0x20:
            psms->ismsNext = -2;
            break;
        default:
            psms->ismsNext = IsmsFindSmRequired(this, psms->oidNext);
            break;
        }
    }
    int grfAll = 0;
    csmt = pbis->U8Read();
    asmt = (SMT *)AllocClearedStackBlock(csmt * sizeof(SMT), 16);
    for (j = 0; j < csmt; j++)
    {
        SMT *psmt = &asmt[j];
        psmt->ismsFrom = IsmsFindSmRequired(this, (OID)pbis->S32Read());
        psmt->ismsTo = IsmsFindSmRequired(this, (OID)pbis->S32Read());
        psmt->grfsmt = pbis->S32Read();
        psmt->grfsmtBreak = pbis->S32Read();
        psmt->gProbability = pbis->F32Read();
        OID oidAseg = (OID)pbis->S32Read();
        if (oidAseg != OID_Nil)
        {
            for (i = 0; i < collector.m_cplo; i++)
            {
                plo = collector.m_aplo[i];
                if (plo->oid == oidAseg)
                {
                    psmt->paseg = (ASEG *)plo;
                    break;
                }
            }
            if (!psmt->paseg)
            {
                j--;
                csmt--;
                continue;
            }
        }
        grfAll |= psmt->grfsmt & 0xfffc;
    }
    asmt = (SMT *)AllocWorldHeapCopy(csmt * sizeof(SMT), 16, asmt);
    LoadOptionsFromBrx(this, pbis);
    int agrf[32];
    int cgrf = 0;
    for (int grfBit = 4; grfBit <= 0x1000; grfBit <<= 1)
    {
        if (grfBit & grfAll)
        {
            for (int igrf = 0; igrf < cgrf; igrf++)
            {
                if (grfBit & agrf[igrf])
                    goto next;
            }
            int grf = grfAll;
            for (j = 0; j < csmt; j++)
            {
                if (asmt[j].grfsmt & grfBit)
                {
                    grf &= asmt[j].grfsmt;
                }
            }
            for (j = 0; j < csmt; j++)
            {
                if ((asmt[j].grfsmt & grf) && !(asmt[j].grfsmt & grfBit))
                {
                    grf &= ~asmt[j].grfsmt;
                }
            }
            agrf[cgrf++] = grf;
        }
    next:;
    }
    csmrt = cgrf;
    asmrt = (SMRT *)AllocWorldHeapBlock(csmrt * sizeof(SMRT), 16);
    for (int ismrt = 0; ismrt < csmrt; ismrt++)
    {
        SMRT *psmrt = &asmrt[ismrt];
        psmrt->grf = agrf[ismrt];
        psmrt->ab = (signed char *)AllocWorldHeapBlock(csms * csms, 16);
        for (int ismsFrom = 0; ismsFrom < csms; ismsFrom++)
        {
            for (int ismsTo = 0; ismsTo < csms; ismsTo++)
            {
                psmrt->ab[ismsFrom * csms + ismsTo] = (ismsFrom == ismsTo) ? 0 : -1;
            }
        }
        for (cstep = 1;; cstep++)
        {
            fChanged = 0;
            for (j = 0; j < csmt; j++)
            {
                SMT *psmt = &asmt[j];
                if (psmt->grfsmt & psmrt->grf)
                {
                    for (i = 0; i < csms; i++)
                    {
                        if (psmrt->ab[i * csms + psmt->ismsFrom] == cstep - 1 && psmrt->ab[i * csms + psmt->ismsTo] < 0)
                        {
                            psmrt->ab[i * csms + psmt->ismsTo] = cstep;
                            fChanged = 1;
                        }
                        else if ((psmt->grfsmt & 1) && psmrt->ab[i * csms + psmt->ismsTo] == cstep - 1 &&
                                 psmrt->ab[i * csms + psmt->ismsFrom] < 0)
                        {
                            psmrt->ab[i * csms + psmt->ismsFrom] = cstep;
                            fChanged = 1;
                        }
                    }
                }
            }
            if (!fChanged)
                break;
        }
    }
}

