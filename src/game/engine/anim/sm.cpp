// Picks a transition out of the current state (or a reversible one) that brings the machine one hop closer to the goal,
// weighted at random among the candidates.
extern "C" int ChooseSmTransitionTowardGoal(SM *p, int mask, int a, int b)
{
    SMT *ap[64];
    int c;
    int i;
    int n;
    if (a == b) n = 1;
    else n = CountSmTransitionHops(p, mask, a, b);
    c = 0;
    for (i = 0; i < p->csmt; i++) {
        SMT *pe = &p->asmt[i];
        if (!(pe->grfsmt & mask)) continue;
        if (pe->ismsFrom == a && CountSmTransitionHops(p, mask, pe->ismsTo, b) == n - 1) {
            ap[c++] = pe;
            continue;
        }
        if ((pe->grfsmt & fsmtReversible) && pe->ismsTo == a && CountSmTransitionHops(p, mask, pe->ismsFrom, b) == n - 1)
            ap[c++] = pe;
    }
    if (c == 0) return 0;
    return ChooseWeightedSmTransition(p, c, ap);
}
