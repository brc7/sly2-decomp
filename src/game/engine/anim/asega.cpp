// Executes one segment event: sounds, rumble, hands-off, applying / seeking / retracting other segments, splice script
// calls, emitters, messages and the like.
// Also known as: FireAsegaEvent (upstream readable / Sly 1 name; FireAsegaEvent__FP5ASEGAP6ASEGEV).
void HandleAsegaEvent(ASEGA *player, EA *event)
{
    GV g(player);
    MSG msg;
    void *pv;
    ASEG *pq;
    int f;
    player->time = event->time;
    pq = player->animation;
    f = 0;
    if (player->speed < 0.0f && event >= pq->aeaFrame)
        f = event < pq->aeaFrame + pq->ceaFrame;
    switch ((unsigned int)event->kind) {
    case 0: {
        LO *v = GetAsegaEventTarget(player);
        EASND *pa = event->pesnd;
        StartSwAsegSound(&g_sw, pa->sfxId, pa->oid, pa->rangeNear, pa->rangeFar, player->rootObject, v, pq, &player->sound, pa->pitch, pa->doppler, pa->volume);
        break;
    }
    case 1:
        StopSwAsegSound(&g_sw, event->pesnd, pq, &player->sound);
        break;
    case 2:
        JoltCamera(&g_cm, event->pesnd);
        break;
    case 3:
        TriggerJoyRumbleRumk__FP3JOY4RUMKf(&g_joy, event->pesnd, event->floatArg2);
        break;
    case 4: {
        LO *po = FindSwObject(&g_sw, 4, event->oid, GetAsegaEventTarget(player));
        if (po) {
            switch (GetBasicCid(po)) {
            case 0x6D:
                ApplyAsegCore((ASEG *)po, 0, 0, 0.0f, 1.0f, 0);
                break;
            case 0x72:
                FireRelay(po, 0);
                break;
            }
        }
        break;
    }
    case 5:
        SeekAsega(player, 0, event->floatArg, event->floatArg2);
        break;
    case 6:
        RetractAsega(player);
        break;
    case 9:
    case 10:
        {
            int fT = (event->kind == 9);
            fT ^= f;
            SetAsegaHandsOff(player, fT);
        }
        break;
    case 7:
    case 8: {
        int fT = (event->kind == 7);
        fT ^= f;
        ShowSwAsegObject(&g_sw, fT, event->pesnd, GetAsegaEventTarget(player), pq, event->floatArg2);
        break;
    }
    case 11: {
        msg.p = player;
        msg.g = event->time;
        msg.n = event->intArg;
        player->SendMessage((MSGID)9, &msg);
        break;
    }
    case 12: {
        { void **ppv = &pv; *ppv = &event->intArg; player->HandleSpliceEvent(4, 0, 1, ppv, 0); }
        break;
    }
    case 17: {
        EA17 *pa = event->pea17;
        SendSwAsegMessage(&g_sw, pa->oid, pa->oid1, pa->oid2, GetAsegaEventTarget(player), pq, pa->value);
        break;
    }
    case 13:
    case 14: {
        int fT = (event->kind == 13);
        fT ^= f;
        ShowSwAsegGlobs(&g_sw, fT, event->pesnd, event->intArg2, player->rootObject, GetAsegaEventTarget(player), pq);
        break;
    }
    case 15:
    case 16: {
        int fT = (event->kind == 15);
        fT ^= f;
        ShowSwAsegParts(&g_sw, fT, event->pesnd, event->intArg2, player->rootObject, GetAsegaEventTarget(player), pq);
        break;
    }
    case 18:
        ShowCountdownHud(&g_sw, player->time);
        break;
    case 19:
        HideCountdownHud(&g_sw);
        break;
    case 20: {
        EA20 *pa = event->pea20;
        SetSwAsegEyesClosed(&g_sw, pa->id0, pa->id1, GetAsegaEventTarget(player), pq, pa->value);
        break;
    }
    case 21:
        EvaluateXfSlotValue(player, event->intArg);
        break;
    case 22:
        SetSoAnimIndex(player->rootObject, event->intArg);
        break;
    case 23:
        SetSoAnimIndex(player->rootObject, -1);
        break;
    case 24:
        if (player->rootObject && IsBasicDerivedFrom(player->rootObject, (CID)0x34)) {
            char *pb = (char *)event->pea24;
            SetStepplayerIdleParams(player->rootObject, pb, pb + 8, pb + 0x10);
        }
        break;
    }
}

