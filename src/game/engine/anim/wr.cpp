// Schlick-style bias curve: remaps u in [0, 1] so that u = 0.5 maps to uBias, keeping 0 and 1 fixed.
float UBias(float u, float bias)
{
    return u / ((((1.0f / bias) - 2.0f) * (1.0f - u)) + 1.0f);
}

