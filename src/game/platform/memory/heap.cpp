// Allocates `size` bytes from `heap` at `alignment` and zero-fills them.
void *AllocZeroedFromHeap(HEAP *heap, int size, int alignment)
{
    void *block = heap->PvAlloc(size, alignment);
    memset(block, 0, size);
    return block;
}

