// Turns both motors off.
void StopRumbleActuators(RUMBLE *rumble)
{
    unsigned char actuators[6];
    actuators[0] = 0;
    actuators[1] = 0;
    scePadSetActDirect(rumble->port, rumble->slot, actuators);
}

