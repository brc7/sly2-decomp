typedef int qword __attribute__((mode(TI)));

/* Payloads of the heap-allocated value kinds: the value, then its reference count. Each kind has its own heap. */
struct VALVECTOR { qword vec; int cref; };                 /* tag 0x1A, CSpliceHeap<0x20, 0x100> */
struct MATRIX4V { float m[4][4]; } __attribute__((aligned(16)));
struct VALMATRIX { MATRIX4V mat; int cref; };               /* tag 0x1B, CSpliceHeap<0x50, 0x100> */
struct VALCLQ { qword clq; int cref; };                     /* tag 0x1C, CSpliceHeap<0x20, 0x40> */
struct LMV { int a, b; };
struct VALLM { LMV lm; int cref; };                         /* tag 0x1D, CSpliceHeap<0xC, 0x40> */
struct SMPV { int a, b, c; };
struct VALSMP { SMPV smp; int cref; };                      /* tag 0x1E, CSpliceHeap<0x10, 0x20> */

#define HEAP_VECTOR (&CSpliceHeap<0x20, 0x100>::s_heap.slotheap)
#define HEAP_MATRIX (&CSpliceHeap<0x50, 0x100>::s_heap.slotheap)
#define HEAP_CLQ (&CSpliceHeap<0x20, 0x40>::s_heap.slotheap)
#define HEAP_LM (&CSpliceHeap<0xC, 0x40>::s_heap.slotheap)
#define HEAP_SMP (&CSpliceHeap<0x10, 0x20>::s_heap.slotheap)

/* A basic (engine) object: reference counting through its vtable (slot 1 adds, slot 2 releases; g++ 2.95 vtable
   entries are {short delta; short pad; pfn}). */
struct VTENTRY { short d; short pad; void (*pfn)(void *); };
struct BASICOBJ { int pad[3]; VTENTRY *vt; };

/* GC view of a pool node: reference count, then a link word with prev/next as (index, page) pairs into the pool's
   blocks and the mark bit. */
struct GCNODE
{
    int cref;
    unsigned prev : 13;
    unsigned prevpg : 2;
    unsigned p1 : 1;
    unsigned next : 13;
    unsigned nextpg : 2;
    unsigned fMark : 1;
};

