/* Counted links as the proc destructor releases them (inline: release, deleting at zero). */
template <class T>
struct SPREL
{
    T *p;
    ~SPREL() { T *pt = p; if (pt && --pt->m_cref == 0) delete pt; }
};

/* A frame as far as this TU deletes one (its destructor is the linkonce 0x257078, emitted by splice/gc.cpp). */
class CFrame
{
public:
    int m_cref;
    ~CFrame();
};

/* A proc (splice/proc.cpp's CProc: frame link at 0x8, parameter and body lists at 0x14/0x18). Its destructor is the
   linkonce 0x257148, defined (inline) at the end of the file, after its callers, which therefore call it. */
struct CProc : CGcObj<CProc>
{
    SPREL<CFrame> frame;
    int cargMin;
    int fRest;
    SPREL<CPair> pparams;
    SPREL<CPair> pbody;
    ~CProc();
};
template <> void CGcObj<CProc>::Unlink();   /* emitted by splice/gc.cpp (declared so this file emits no copy) */

/* A native method (tag 0x22): counted, freed into the sixth engine pool. */
struct CMethod
{
    int cref;
};

