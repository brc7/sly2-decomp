// Returns the value coerced to an integer (floats truncated).
extern "C" CRef *CRef_CoerceS32(CRef *pref, CRef *source)
{
    if (source->m_tagk == 0x15)
    {
        __4CRefRC4CRef(pref, source);
    }
    else
    {
        float g = source->u.g;
        pref->m_tagk = 0x15;
        pref->u.n = (int)g;
    }
    return pref;
}

// Returns the value coerced to a float (integers promoted); the numeric built-ins use it.
extern "C" CRef *CRef_CoerceF32(CRef *pref, CRef *source)
{
    if (source->m_tagk == 0x16)
    {
        __4CRefRC4CRef(pref, source);
    }
    else
    {
        pref->u.g = (float)source->u.n;
        pref->m_tagk = 0x16;
    }
    return pref;
}

// Takes a reference on the payload according to its tag (box counts, pair/proc/method counts, objects via vtable
// slot 1).
void CRef::Incref()
{
    switch (m_tagk)
    {
    case 0x1B:
        ((VALMATRIX *)u.pv)->cref++;
        break;
    case 0x1A:
    case 0x1C:
        ((VALVECTOR *)u.pv)->cref++;
        break;
    case 0x1D:
        ((VALLM *)u.pv)->cref++;
        break;
    case 0x1E:
        ((VALSMP *)u.pv)->cref++;
        break;
    case 0x21:
    {
        BASICOBJ *object = (BASICOBJ *)u.pv;
        if (object)
            object->vt[1].pfn((char *)object + object->vt[1].d);
        break;
    }
    case 0x1F:
    case 0x20:
    case 0x22:
        (*(int *)u.pv)++;
        break;
    }
}

// Releases the payload according to its tag; a box, pair, proc or method whose count reaches zero is freed into its
// pool, objects are released through their vtable.
void CRef::Decref()
{
    switch (m_tagk)
    {
    case 0x1A:
    {
        VALVECTOR *p = (VALVECTOR *)u.pv;
        if (--p->cref == 0)
            FreeSlotheapSlot(HEAP_VECTOR, p);
        break;
    }
    case 0x1B:
    {
        VALMATRIX *p = (VALMATRIX *)u.pv;
        if (--p->cref == 0)
            FreeSlotheapSlot(HEAP_MATRIX, p);
        break;
    }
    case 0x1C:
    {
        VALCLQ *p = (VALCLQ *)u.pv;
        if (--p->cref == 0)
            FreeSlotheapSlot(HEAP_CLQ, p);
        break;
    }
    case 0x1D:
    {
        VALLM *p = (VALLM *)u.pv;
        if (--p->cref == 0)
            FreeSlotheapSlot(HEAP_LM, p);
        break;
    }
    case 0x1E:
    {
        VALSMP *p = (VALSMP *)u.pv;
        if (--p->cref == 0)
            FreeSlotheapSlot(HEAP_SMP, p);
        break;
    }
    case 0x1F:
    {
        CPair *p = (CPair *)u.pv;
        if (--p->m_cref == 0)
            delete p;
        break;
    }
    case 0x20:
    {
        CProc *p = (CProc *)u.pv;
        if (--p->m_cref == 0)
            delete p;
        break;
    }
    case 0x21:
    {
        BASICOBJ *p = (BASICOBJ *)u.pv;
        if (p)
            p->vt[2].pfn((char *)p + p->vt[2].d);
        break;
    }
    case 0x22:
    {
        CMethod *p = (CMethod *)u.pv;
        if (--p->cref == 0 && p)
        {
            Unlink__t6CGcObj1Z7CMethod((GCNODE *)p);
            FreeSlotheapSlot(&CSlotPool<0x14, 0x100>::s_pool.slotheap, p);
        }
        break;
    }
    }
}

// Releases the old payload and sets a new tag; boxed tags (0x1A..0x1E) get a fresh box from their pool.
void CRef::SetTag(TAGK tagk)
{
    m_tagk = tagk;
    switch (tagk)
    {
    case 0x1A:
    {
        VALVECTOR *p = (VALVECTOR *)AllocZeroedFromSlotheap(HEAP_VECTOR);
        p->cref = 0;
        u.pv = p;
        p->cref++;
        break;
    }
    case 0x1B:
    {
        VALMATRIX *p = (VALMATRIX *)AllocZeroedFromSlotheap(HEAP_MATRIX);
        p->cref = 0;
        u.pv = p;
        p->cref++;
        break;
    }
    case 0x1C:
    {
        VALCLQ *p = (VALCLQ *)AllocZeroedFromSlotheap(HEAP_CLQ);
        p->cref = 0;
        u.pv = p;
        p->cref++;
        break;
    }
    case 0x1D:
    {
        VALLM *p = (VALLM *)AllocZeroedFromSlotheap(HEAP_LM);
        p->cref = 0;
        u.pv = p;
        p->cref++;
        break;
    }
    case 0x1E:
    {
        VALSMP *p = (VALSMP *)AllocZeroedFromSlotheap(HEAP_SMP);
        p->cref = 0;
        u.pv = p;
        p->cref++;
        break;
    }
    case 0x1F:
    case 0x20:
    case 0x21:
    case 0x22:
    case 0x23:
    default:
        u.pv = 0;
        break;
    }
}

