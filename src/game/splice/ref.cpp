struct VECTOR3V { float x, y, z; };
struct VECTOR2V { float x, y; };

// Value equality: same tag and equal payload (numbers, symbols, objects by identity, boxed vectors and matrices by
// contents).
bool CRef::operator==(const CRef &ref)
{
    if (m_tagk != ref.m_tagk)
        return false;
    switch (m_tagk)
    {
    case 0x15: case 0x16: case 0x17: case 0x18: case 0x19:
    case 0x1F: case 0x20: case 0x21: case 0x22: case 0x23:
        return u.n == ref.u.n;
    case 0x1B:
        return func_00233178(u.pv, ref.u.pv, 0x40) == 0;
    case 0x1D:
    {
        VECTOR2V *pa = (VECTOR2V *)u.pv, *pb = (VECTOR2V *)ref.u.pv;
        return pa->x == pb->x && pa->y == pb->y;
    }
    case 0x1A: case 0x1C: case 0x1E:
    {
        VECTOR3V *pa = (VECTOR3V *)u.pv, *pb = (VECTOR3V *)ref.u.pv;
        return pa->x == pb->x && pa->y == pb->y && pa->z == pb->z;
    }
    }
    return true;
}

// Deep copy of a value: boxes are re-allocated, pairs and procs cloned recursively (CPair_CloneTo, CProc_CloneTo),
// objects re-referenced. Used when cloning objects with their Splice state.
CRef CRef_CloneTo(CRef *pref, void *a, void *b)
{
    switch (pref->m_tagk)
    {
    case 0x1A: return CRef((const VECTOR *)pref->u.pv);
    case 0x1B: return CRef((const MATRIX4 *)pref->u.pv);
    case 0x1C: return CRef((const CLQ *)pref->u.pv);
    case 0x1D: return CRef((const LM *)pref->u.pv);
    case 0x1E: return CRef((const SMP *)pref->u.pv);
    case 0x1F: return CRef(CPair_CloneTo((CPair *)pref->u.pv, a, b).p);
    case 0x20: return CRef(CProc_CloneTo((CProc *)pref->u.pv, a).p);
    case 0x21: return CRef((BASIC *)pref->u.pv);
    }
    return CRef(*pref);
}

