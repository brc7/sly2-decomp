/** @sly2-annot addr=0x1286E0
 * Purpose: Full collection: allocate mark stacks, UnmarkAll on 6 splotheaps, mark roots
 *   (frames/sidebags/stack), MarkLiveObjects, FreeGarbage on all heaps
 * Info: proposed name CGc_Collect (T1); class CGc; TU gc
 * Confidence: high [T1 0.85] - evidence: static analysis; sources: r1_116918
 * See: docs/reference/functions/splice-scripting.md#gc-0x128138-0x128b60
 * @end-sly2-annot */
void CGc::Collect()
{
    STACKSCOPE ss;
    GCHDR *pn;
    ENV *penv;
    ROOT *pr;
    fMark = !fMark;
    func_002574E0();
    func_002574E8();
    func_002574F0();
    func_002574F8();
    func_00257500();
    func_00257508();
    STACKSCOPE_ctor(&ss);
    InitMarkStack(&cFrame, (void ***)&apFrame, D_00452108);
    InitMarkStack(&cNode, (void ***)&apNode, D_004520B8);
    apClo = (CLO **)PvAllocMarkStack(D_00452130);
    cClo = 0;
    for (pn = D_002DD2AC; pn;)
    {
        if (pn->fMark != D_002DD598.fMark)
        {
            pn->fMark = D_002DD598.fMark;
            apFrame[cFrame++] = (FRAME *)pn;
        }
        {
            GCHDR *pnNext = PgcFromFrameHandle(pn->next, pn->nextpg);
            pn = pnNext;
        }
    }
    for (penv = D_002DD2CC; penv;)
    {
        BIND *pb;
        if (penv->fMark != D_002DD598.fMark)
            penv->fMark = D_002DD598.fMark;
        for (pb = penv->pbFirst; pb; pb = pb->pbNext)
        {
            pb->fMark = D_002DD598.fMark;
            func_001285D8(this, &pb->ref);
        }
        {
            ENV *penvNext = (ENV *)PgcFromSidebagHandle(penv->next, penv->nextpg);
            penv = penvNext;
        }
    }
    for (pr = D_003E0E80; pr; pr = pr->prNext)
    {
        NODE *p = pr->pobj;
        if (p->fMark != D_002DD598.fMark)
        {
            p->fMark = D_002DD598.fMark;
            apNode[cNode++] = p;
        }
    }
    MarkLiveObjects();
    func_00257510();
    func_00257678();
    func_002577E0();
    func_00257948();
    func_00257AB0();
    func_00257C18();
    STACKSCOPE_ctor_1AE4A0(&ss, 2);
}

