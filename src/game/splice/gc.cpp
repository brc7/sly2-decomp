/* GC header of every collected node: reference count, then a link word holding prev/next as (index, page) pairs into
   the pool's block table and the mark bit (a node is live when fMark equals g_gc.fMark). */
struct GCHDR
{
    int cref;
    unsigned prev : 13;
    unsigned prevpg : 2;
    unsigned p1 : 1;
    unsigned next : 13;
    unsigned nextpg : 2;
    unsigned fMark : 1;
};

struct BIND;
struct FRAME;
struct NODE;
struct CLO;

/* Binding (CVarb, pool 1). */
struct BIND : GCHDR
{
    int sym;
    CRef ref;
    BIND *pbNext;
};

/* Frame (CFrame, pool 2). */
struct FRAME : GCHDR
{
    int c;
    FRAME *apf[4];
    BIND *pbFirst;
};

/* Pair (CPair, pool 0). */
struct NODE : GCHDR
{
    CRef car;
    NODE *pnNext;
};

/* Link of a proc's list. */
struct LINK : GCHDR
{
    int x8;
    int xC;
    LINK *plNext;
};

/* Proc / closure (CProc, pool 3). */
struct CLO : GCHDR
{
    FRAME *pf;
    int xC;
    int x10;
    LINK *pl;
    NODE *pn;
};

/* Sidebag (pool 4, 0xC bytes). */
struct ENV : GCHDR
{
    BIND *pbFirst;
};

/* External root: a counted reference to a node. */
struct ROOT
{
    int x0;
    int x4;
    NODE *pobj;
    int xC;
    ROOT *prNext;
};

struct CGc
{
    /* 0x00 */ unsigned int fMark;  /* current mark, flipped by every collection */
    /* 0x04 */ int cFrame;          /* mark stacks (allocated per collection) */
    /* 0x08 */ FRAME **apFrame;
    /* 0x0C */ int cNode;
    /* 0x10 */ NODE **apNode;
    /* 0x14 */ int cClo;
    /* 0x18 */ CLO **apClo;

    CGc() { CGc_ctor(this); }
    void MarkLiveObjects();
    void Collect();
};

