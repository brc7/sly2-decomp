/* CRef as the thunks use it (the per-function files' declarations, merged): sly2/cref.h's CRef has the same layout
   and inline members, but not the assignments by payload type that the thunks call (operator=(void *), (qword),
   (int), (float)); adding those overloads to cref.h could change overload resolution in its other includers. */
struct CRef
{
    int m_tagk;
    union { int n; float g; void *pv; } u;
    CRef() { m_tagk = -1; }
    CRef(int tagk) { InitTag(tagk); }
    CRef(const CRef &r);
    void Decref();
    void InitTag(int tagk);
    ~CRef() { Decref(); }
    CRef &operator=(const CRef &r);
    CRef &operator=(void *pv);
    CRef &operator=(qword q);
    CRef &operator=(bool f);
    CRef &operator=(int n);
    CRef &operator=(float g);
};
