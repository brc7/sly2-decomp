{
    return id >> 0x10;
}

// Returns the copy index of a proxy id (low half).
extern "C" short GetCopyIndexFromProxyId(int id)
{
    return id;
}

// Returns the oid of a proxy id's copy, or -1 when there is no copy.
/* The oid of a proxy id's copy (-1 for no copy). */
