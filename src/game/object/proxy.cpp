// LO slot 25: move the object to proxy id idProxy in the world's proxy-reference tree (detaching it from its old path
// and claiming the new one where the source has a single object), optionally for its children too.
void LO::SetIdProxy(int idProxy, int fChildren)
{
    int aid[16];
    int cid = 16;
    PXR *ppxrIter;
    for (ppxrIter = proxyRecord; ppxrIter; ppxrIter = ppxrIter->parent)
    {
        if (ppxrIter->proxyId == -1)
        {
            break;
        }
        aid[--cid] = ppxrIter->proxyId;
    }
    aid[--cid] = idProxy;
    PXR *ppxrNew = FindPxr(g_sw.ppxrRoot, 16 - cid, &aid[cid]);
    for (ppxrIter = proxyRecord; ppxrIter->proxyId != -1; ppxrIter = ppxrIter->parent)
    {
        if (ppxrIter->object == this)
        {
            ppxrIter->object = 0;
        }
        else
        {
            break;
        }
    }
    for (ppxrIter = ppxrNew; ppxrIter->proxyId != -1; ppxrIter = ppxrIter->parent)
    {
        if (PproxysrcFromIdProxy(ppxrIter->proxyId)->cplo == 1 && !ppxrIter->object)
        {
            ppxrIter->object = this;
        }
        else
        {
            break;
        }
    }
    proxyRecord = ppxrNew;
    if (fChildren)
    {
        STACKSCOPE scope;
        LO **aplo;
        int cplo = GetChildren(&aplo);
        for (int iplo = 0; iplo < cplo; iplo++)
        {
            aplo[iplo]->SetIdProxy(idProxy, 1);
        }
    }
}

