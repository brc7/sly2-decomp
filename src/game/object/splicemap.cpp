extern "C" CRef EvalExpression__FP5CPairP6CFrame(CPair *ppair, CFrame *pframe);

// Creates the world's root Splice frame and keeps a reference to it. Called when a level body is loaded.
// Also known as: StartupSwSplice (upstream readable / Sly 1 name; StartupSwSplice__FP2SW).
extern "C" void InitSwSpliceFrame(SW *world)
{
    world->unknown3A14 = 1;
    world->scriptFrame = CGcObj<CFrame>::PtNew();
    world->scriptFrame.m_p->MakeRoot();
}

// Clears the world's Splice table pointer before a level load. (inferred)
// Also known as: ShutdownSwSplice (upstream readable / Sly 1 name; ShutdownSwSplice__FP2SW).
extern "C" void ClearSwSpliceTable(SW *world)
{
    world->unknown3A14 = 0;
}

// Releases the world's root Splice frame and shuts the Splice VM down. Called when the world is deleted.
extern "C" void DeleteSwSplice(SW *world)
{
    world->scriptFrame = 0;
    ShutdownSplice();
}

// Reads the level's Splice section: the entry count, then each entry's frame and value (LoadSpliceEntryFromBrx), into
// a table on the world heap. Layout parse-verified: a parser following it reads every byte of 4 levels.
// Also known as: LoadSwSpliceFromBrx (upstream readable / Sly 1 name;
//   LoadSwSpliceFromBrx__FP2SWiP18CBinaryInputStream).
extern "C" void LoadSwSpliceFromBrx(SW *world, int a, void *stream)
{
    int c = U32Read__18CBinaryInputStream(stream);
    int i;
    SPLCS *psplcs;
    if (!c) return;
    {
        SZ sz(0x10, 0x10);
        psplcs = AllocClearedFromWorldHeap(&sz);
    }
    psplcs->a = a;
    CRef r;
    psplcs->c = c;
    {
        SZ sz(c * 8, 0x10);
        psplcs->ae = AllocFromWorldHeap(&sz);
    }
    for (i = 0; i < c; i++) {
        SPLCE *pe = &psplcs->ae[i];
        SPPAIR sp = DeserializePair__FP18CBinaryInputStream(stream);
        CPair *q = sp.p;
        if (q) q->m_cref++;
        pe->ppair = sp.p;
        pe->pframe = 0;
        if (D_003E1C34) {
            CBinaryInputStream_SkipStringSw(stream);
            CBinaryInputStream_SkipStringSw(stream);
            CBinaryInputStream_SkipStringSw(stream);
        }
    }
    for (i = 0; i < c; i++) {
        LoadSpliceEntryFromBrx(world, psplcs, i);
    }
    world->psplcs = psplcs;
    psplcs->psplcsNext = world->psplcsHead;
    world->psplcsHead = psplcs;
    CGc_UpdateRecyclable(&g_gc);
}

// Returns the Splice frame of table entry index (null for -1); objects get their frame from it at creation.
extern "C" CFrame *GetSpliceFrame(SW *world, int i)
{
    if (i == -1) return 0;
    return world->psplcs->ae[i].pframe;
}

