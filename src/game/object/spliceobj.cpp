/* SetValuesFromSplice (RefSetPvsFromSplice): store each of c values into apv[i] as type aotyp[i] (int and float coerced,
   the vector/matrix/clq/lm/smp payloads copied, a CRef assigned); returns the void reference. */
struct M3Q { qword a[3]; };
struct V2 { int a, b; };
struct V3 { int a, b, c; };
// Stores each of count Splice values into the pointed-to variables as their given types (ints and floats coerced,
// vector/matrix/clq/lm/smp payloads copied, CRefs assigned); returns Void.
CRef SetValuesFromSplice(int c, CRef *aref, OTYP *aotyp, void **apv)
{
    CRef ref;
    int i;
    for (i = 0; i < c; i++) {
        int ot;
        void *pv;
        ref = aref[i];
        ot = aotyp[i];
        pv = apv[i];
        switch (ot) {
        case 5: case 6: case 7: case 8:
        case 0xE: case 0xF: case 0x10: case 0x11:
        case 0x13: case 0x14: case 0x15:
            if (ref.m_tagk == 0x15) {
                *(int *)pv = ref.u.n;
            } else {
                CRef t;
                t = CoerceS32(&ref);
                *(int *)pv = t.u.n;
            }
            break;
        case 1:
            if (ref.m_tagk == 0x16) {
                *(float *)pv = ref.u.g;
            } else {
                CRef t;
                t = CoerceF32(&ref);
                *(float *)pv = t.u.g;
            }
            break;
        case 4:
            *(M3Q *)pv = *(M3Q *)ref.u.pmat;
            break;
        case 2:
        case 9:
            *(qword *)pv = *(qword *)ref.u.pv;
            break;
        case 0xA:
            *(V2 *)pv = *(V2 *)ref.u.plm;
            break;
        case 0xB:
            *(V3 *)pv = *(V3 *)ref.u.psmp;
            break;
        default:
            if (ot & 0x8000)
                *(CRef *)pv = ref;
            else if (ot & 0x1000)
                goto store;
            else if (ot & 0x2000)
        case 0:
            store:
                *(int *)pv = ref.u.n;
            break;
        case 0xD:
        case 0x16:
            break;
        }
    }
    return CRef(0x24);
}

/* EE (single-float EABI) stdarg, from gcc's va-mips.h. */
typedef char *va_list;
#define va_start(ap, last) (ap = ((char *)__builtin_next_arg(last) - (__builtin_args_info(2) >= 8 ? 0 : (8 - __builtin_args_info(2)) * 8)))

/* The c destination pointers come as variable arguments. */
// Varargs form of SetValuesFromSplice: the destination pointers follow the type array.
CRef RefSetArgsFromSplice(int c, CRef *aref, OTYP *aotyp, ...)
{
    va_list ap;
    void *apv[32];
    int i;
    va_start(ap, aotyp);
    for (i = 0; i < c; i++) {
        ap += 8;
        apv[i] = *(void **)(ap - 8);
    }
    return SetValuesFromSplice(c, aref, aotyp, apv);
}

/* Convert each element of a Splice list into apv[*pc] (one type for all); returns the void reference. */
struct SPLLIST { int c; CPair *ppairFirst; };
// Converts each element of a Splice list into the destination array with one type; returns Void.
CRef SetValuesFromSpliceList(SPLLIST *plist, OTYP otyp, int nUnused, int *pc, void **apv) __asm__("SetValuesFromSpliceList");
CRef SetValuesFromSpliceList(SPLLIST *plist, OTYP otyp, int nUnused, int *pc, void **apv)
{
    if (plist->c == 0) {
        *pc = 0;
        return CRef(0x24);
    }
    *pc = 0;
    for (CPair *pair = plist->ppairFirst; pair; pair = pair->next.p) {
        CRef ref;
        ref = RefSetArgsFromSplice(1, &pair->ref, &otyp, &apv[*pc]);
        ++*pc;
    }
    return CRef(0x24);
}

