// True unless the capture is in its closing states (2 or 3); the main loop uses it to decide whether to draw
// normally. (inferred)
extern "C" int IsFrameCaptureInactive(P *capture)
{
    switch (capture->state) {
    case 2:
    case 3:
        return 0;
    }
    return 1;
}

