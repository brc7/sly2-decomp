class CRef {
public:
    int m_tagk;
    int m_tag;
    CRef(int tagk, int n) { m_tagk = tagk; m_tag = n; }
    CRef(const CRef &ref);   /* out of line: __4CRefRC4CRef (ref.cpp) */
    ~CRef() { Decref__4CRef(this); }
};
