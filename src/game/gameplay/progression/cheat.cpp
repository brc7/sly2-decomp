/* One cheat code (0x38 bytes; 15 static codes from D_002BD4E0). */
struct CODE
{
    int *abtn;              /* +0x0 button sequence */
    int cbtn;               /* +0x4 */
    void (*pfn)(void *);    /* +0x8 action */
    void *pv;               /* +0xC its argument */
    int ibtn;               /* +0x10 buttons matched so far */
    int fRemove;            /* +0x14 one-shot: unlink after firing */
    CODE *pcodeNext;        /* +0x18 SL link */
    char pad[0x38 - 0x1C];
};
typedef char assert_CODE_size[sizeof(CODE) == 0x38 ? 1 : -1];

/* The code list: an SL of CODEs and the time the last button was pressed + 1 s (0: idle). */
struct CODES
{
    SL sl;                  /* +0x0 */
    float tMatch;           /* +0xC */
};

/* Safe iterator over an SL (the SL counterpart of sly2/dli.h; its own stack at D_002DD2F8). */
struct SLI { SL *m_psl; void **m_ppv; int m_ibSle; SLI *m_psliNext; };
extern SLI *D_002DD2F8;
// Starts a safe iteration over an SL: pushes the iterator on the iterator stack D_002DD2F8.
static inline void InitSli(SLI *psli, SL *psl)
{
    psli->m_psl = psl;
    psli->m_ppv = (void **)psl;
    psli->m_ibSle = psl->ibSle;
    psli->m_psliNext = D_002DD2F8;
    D_002DD2F8 = psli;
}
// Returns the current element and advances the iterator to the next one.
static inline void *PvNextSli(SLI *psli)
{
    void *pv = *psli->m_ppv;
    psli->m_ppv = (void **)((char *)pv + psli->m_ibSle);
    return pv;
}

