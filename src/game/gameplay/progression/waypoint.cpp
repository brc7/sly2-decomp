// Moves an int into a VU register.
static inline qwordV QI(int i)
{ qwordV r; __asm__("qmtc2.ni %1,%0" : "=j"(r) : "rV"(i)); return r; }
// base + up * k.x.
static inline qwordV AddUp(qwordV base, qwordV up, qwordV k)
{ qwordV r; __asm__("vadda.xyzw ACC,%1,$vf0\n\tvmaddx.xyzw %0,%2,%3x" : "=j"(r) : "j"(base), "j"(up), "j"(k)); return r; }
// base + up * k.x (up also listed as an input, register-order variant).
static inline qwordV AddUpU(qwordV base, qwordV up, qwordV k)
{ qwordV r; __asm__("vadda.xyzw ACC,%1,$vf0\n\tvmaddx.xyzw %0,%2,%3x" : "=j"(r) : "j"(base), "j"(up), "j"(k), "j"(up)); return r; }
// Per-lane maximum (xyz).
static inline qwordV Max(qwordV a, qwordV b)
{ qwordV r; __asm__("vmax.xyz %0,%1,%2" : "=j"(r) : "j"(a), "j"(b)); return r; }
// Per-lane minimum (xyz).
static inline qwordV Min(qwordV a, qwordV b)
{ qwordV r; __asm__("vmini.xyz %0,%1,%2" : "=j"(r) : "j"(a), "j"(b)); return r; }
// Cross product.
static inline qwordV Cross(qwordV a, qwordV b)
{ qwordV r; __asm__("vopmula.xyz ACC,%1,%2\n\tvopmsub.xyz %0,%2,%1" : "=j"(r) : "j"(a), "j"(b)); return r; }
// Unit vector of v.
static inline qwordV Normalize(qwordV v)
{
    qwordV d, one, r;
    __asm__("vmul.xyz %0,%2,%2\n\tvaddw.x %1,$vf0,$vf0w\n\tvadday.x ACC,%0,%0y\n\tvmaddz.x %0,%1,%0z" : "=j"(d), "=&j"(one) : "j"(v));
    __asm__("vsqrt Q,%1x\n\tvwaitq\n\tvaddq.x %1,$vf0,Q\n\tvdiv Q,$vf0w,%1x\n\tvwaitq\n\tvmulq.xyzw %0,%2,Q" : "=&j"(r), "+j"(d) : "j"(v));
    return r;
}
// Lane z of a 128-bit EE register as a float.
// Lane x as a float.
// Length of the xy part of a vector.
static inline float LenXY(qwordV v)
{
    qwordV d, l;
    __asm__("vmul.xy %0,%1,%1\n\tvaddy.x %0,%0,%0y" : "=j"(d) : "j"(v));
    __asm__("vsqrt Q,%1x\n\tvwaitq\n\tvaddq.x %0,$vf0,Q" : "=j"(l) : "j"(d));
    return QwordX(l);
}
// Signed distance of pos from a plane (xyz normal, w offset); also returns the VU temporaries (variant A, register
// order for the match).
static inline float PlaneDistA(UQ &r, UQ &one, qwordV plane, qwordV pos)
{
    qwordV g, o;
    InitVuTemp(&r);
    InitVuTemp(&one);
    __asm__("vmul.xyz %0,%2,%3\n\tvaddw.x %1,$vf0,$vf0w\n\tvadday.x ACC,%0,%0y\n\tvmaddaz.x ACC,%1,%0z\n\tvmsubw.x %0,%1,%2w"
            : "=j"(g), "=j"(o) : "j"(plane), "j"(pos));
    float f = VuToFloat(g);
    one.q = o;
    r.q = g;
    return f;
}

// Same as PlaneDistA with a different register order (variant B).
static inline float PlaneDistB(UQ &r, UQ &one, qwordV plane, qwordV pos)
{
    qwordV g, o;
    InitVuTemp(&r);
    InitVuTemp(&one);
    __asm__("vmul.xyz %0,%2,%3\n\tvaddw.x %1,$vf0,$vf0w\n\tvadday.x ACC,%0,%0y\n\tvmaddaz.x ACC,%1,%0z\n\tvmsubw.x %0,%1,%2w"
            : "=j"(g), "=j"(o) : "j"(plane), "j"(pos));
    float f = QwordX(g);
    __asm__("" : "+j"(g), "+j"(o));
    one.q = o;
    r.q = g;
    return f;
}

// Same as PlaneDistA (variant S).
static inline float PlaneDistS(UQ &r, UQ &one, qwordV plane, qwordV pos)
{
    qwordV g, o;
    InitVuTemp(&r);
    InitVuTemp(&one);
    __asm__("vmul.xyz %0,%2,%3\n\tvaddw.x %1,$vf0,$vf0w\n\tvadday.x ACC,%0,%0y\n\tvmaddaz.x ACC,%1,%0z\n\tvmsubw.x %0,%1,%2w"
            : "=j"(g), "=j"(o) : "j"(plane), "j"(pos));
    float f = QwordX(g);
    one.q = o;
    r.q = g;
    return f;
}


// ZOfN/LenXYFN: n (the loaded count) is an allocation-only operand (6 extra reads on the last asm) so its local-alloc priority
// log2(refs)*refs/life beats the z/len temps (cpso v0, z v1, len a0); t is a TI temp (qty size 2) so z is allocated before len.
// Lane z as a float (with n as an allocation-only operand).
static inline float ZOfN(qwordV v, int n)
{ qwordV t; float z; __asm__("qmfc2.ni %0,%1\n\tpextuw %0,$zero,%0" : "=r"(t) : "j"(v));
  __asm__("mtc1 %1,%0" : "=f"(z) : "r"(t)); return z; }
// Length of the xy part, with the count n as an allocation-only operand (see above).
static inline float LenXYFN(qwordV v, int n)
{
    qwordV d, l;
    int i; float f;
    __asm__("vmul.xy %0,%1,%1\n\tvaddy.x %0,%0,%0y" : "=j"(d) : "j"(v));
    __asm__("vsqrt Q,%1x\n\tvwaitq\n\tvaddq.x %0,$vf0,Q" : "=j"(l) : "j"(d));
    __asm__("qmfc2.ni %0,%1" : "=r"(i) : "j"(l));
    __asm__("mtc1 %1,%0" : "=f"(f) : "r"(i), "r"(n), "r"(n), "r"(n), "r"(n), "r"(n), "r"(n));
    return f;
}

// How much taller the waypoint beam must be to be seen over the scenery from the camera (see the block comment above);
// computed once per camera frame.
extern "C" void CalculateWayptCurtainExtraHeight(O *waypoint)
{
    UQ corner[4];
    UQ side[4];
    UQ tmp;
    FRAME frame;
    UQ normalScratch;
    struct { int numObjects; O **objects; int faceBudget; FACE **faceCursor; } query;   /* one aggregate (stack layout) */

    CM *camera = &g_cm;
    if (waypoint->clipFrame == camera->cplook.numActivations)
        return;
    waypoint->clipFrame = camera->cplook.numActivations;
    qwordV posCam = *(qwordV *)&camera->pos;
    O *source = waypoint->source;
    register qwordV rr asm("$6");   // pin: PosLoWorld result lives in a2 (3rd arg of InitPlaneFromPositions); later uses reload from the 0x190 slot
    if (source)
        rr = GetLoWorldPos(source);
    else
        rr = GetLoWorldPos(waypoint);
    qwordV posSrc = rr;
    UQ *planeOut = &tmp;   // &tmp taken here, not at the call: it (and its gcse copy for preq) then issues before the corner stores
    waypoint->hasCurtainHit = 0;
    waypoint->height = 0.0f;

    corner[0].q = posSrc;
    qwordV up = D_002A2DC0;
    qwordV k = QI(D_002C4490);
    // both corners first, then the stores: k and c2 die at their stores (sched1 issues them first, k before c2)
    qwordV v1 = AddUpU(posSrc, up, k);
    qwordV v2 = AddUpU(posCam, up, k);
    tmp.q = k;
    corner[2].q = v2;
    corner[1].q = v1;
    corner[3].q = posCam;
    InitPlaneFromPositions(planeOut, posCam, posSrc, corner[1].q);
    qwordV plane = tmp.q;
    P4 pvA, pvB;

    int i;
    FACE **faces;
    int objectIndex;
    int numFaces;
    int j;
    EDGE *edge;
    for (i = 0; i < 4; i++) {
        UQ *corners = corner;
        qwordV cornerEdge = VuSub(corners[(i + 1) % 4].q, corners[i].q);
        DefaultConstructVector(&normalScratch);
        normalScratch.q = plane;
        InitPlaneFromNormalPos(&side[i], Normalize(Cross(cornerEdge, plane)), corners[i].q);
    }
    objectIndex = 0;
    STACKSCOPE_ctor(&frame);
    REQ *preq = (REQ *)&tmp;
    preq->cb = 0x10000;
    preq->align = 16;
    faces = (FACE **)AllocFromStack(preq);
    qwordV k2 = QI(D_002C4490);
    tmp.q = k2;
    IntersectSwBoundingBox(&D_003DD490, Min(posCam, posSrc), AddUp(Max(posCam, posSrc), D_002A2DC0, k2),
                  HasCameraBsp, 0, &query.numObjects, &query.objects);
    qwordV toSource = VuSub(posSrc, posCam);
    int numFound = query.numObjects;
    float maxSlope = ZOfN(toSource, numFound) / LenXYFN(toSource, numFound);
    float baseSlope = maxSlope;
    for (; objectIndex < query.numObjects; objectIndex++) {
        O *object = query.objects[objectIndex];
        query.faceBudget = 0x4000;
        query.faceCursor = faces;
        TREE *tree = &object->tree;
        int result = CollectBspSurfacesTouchingPolygon(tree->nodes, tree->nodes + tree->numNodes, 4, corner, &query.faceBudget, &query.faceCursor);
        switch (result) {
        case 0:         /* out of room: give up for this frame */
            STACKSCOPE_ctor_1AE4A0(&frame, 2);
            return;
        case 1:         /* no face touches the curtain */
            continue;
        case 2:
            break;
        }
        numFaces = query.faceCursor - faces;
        UQ d[6][2];
        for (j = 0; j < numFaces; ) {
            edge = faces[j]->firstEdge;
            int jx = j;
            __asm__("" : "+r"(jx) : "r"(edge));
            int nextJ = jx + 1;
            for (; edge; edge = edge->next) {
                FACE *face = &object->faces[edge->faceIndex];
                if (!(face->flags & FACE_FLAG_CANDIDATE))
                    continue;
                int indexA = edge->vertexA;
                int indexB = edge->vertexB;
                P4 *vertices = (P4 *)object->vertices;
                P4 *vertexPtrA = (P4 *)(((int)indexA << 4) + (int)vertices);   /* integer address sums: &vertices[i] schedules differently */
                P4 *vertexPtrB = (P4 *)(((int)indexB << 4) + (int)vertices);
                P4 vertexA = *vertexPtrA;
                P4 vertexB = *vertexPtrB;
                pvA = vertexA;
                pvB = vertexB;
                float distA = PlaneDistA(d[0][0], d[0][1], plane, pvA.q);
                float distB = PlaneDistB(d[1][0], d[1][1], plane, pvB.q);
                if (0.0f < distA && 0.0f < distB)
                    continue;
                if (distA < 0.0f && distB < 0.0f)
                    continue;
                float crossing = distA / (distA - distB);
                qwordV qa = VuFromFloat<qwordV>(1.0f - crossing);
                tmp.q = qa;
                qwordV qb = VuFromFloat<qwordV>(crossing);
                tmp.q = qb;
                qwordV crossPos;
                __asm__("vmulax.xyzw ACC,%1,%3x\n\tvmaddx.xyzw %0,%2,%4x" : "=j"(crossPos) : "j"(pvA.q), "j"(pvB.q), "j"(qa), "j"(qb));
                int isInside = 0;
                if (PlaneDistS(d[2][0], d[2][1], side[0].q, crossPos) < 0.0f &&
                    PlaneDistS(d[3][0], d[3][1], side[1].q, crossPos) < 0.0f &&
                    PlaneDistS(d[4][0], d[4][1], side[2].q, crossPos) < 0.0f &&
                    PlaneDistS(d[5][0], d[5][1], side[3].q, crossPos) < 0.0f)
                    isInside = 1;
                if (isInside) {
                    qwordV toCrossing = VuSub(crossPos, posCam);
                    float slope = QwordZ(toCrossing) / LenXY(toCrossing);
                    if (maxSlope < slope)
                        maxSlope = slope;
                }
            }
            j = nextJ;
        }
        for (j = 0; j < numFaces; j++)
            faces[j]->flags &= ~FACE_FLAG_CANDIDATE;
    }
    waypoint->hasCurtainHit = 1;
    waypoint->height = (maxSlope - baseSlope) * LenXY(VuSub(posCam, posSrc));
    STACKSCOPE_ctor_1AE4A0(&frame, 2);
}

