// CID100 damage handler: a flying or stuck gadget detonates. Always absorbs the damage.
extern "C" int TakeTossableDamage(CID100V *gadget)
{
    switch (gadget->state) {
    case TOSSABLE_FLYING:
    case TOSSABLE_STUCK:
        SetStateVirtual(gadget, TOSSABLE_DETONATE);
    }
    return 1;
}

