// LASEN::RenderSelf (vtable slot 19): RenderSoSelf + draw each visible beam (frustum test, beam matrix). (inferred)
extern "C" void RenderLasenSelf(LASENV *laser)
{
    RenderSoSelf(laser);
    SOTREEV *bound = laser->ptree;
    if (!bound) return;
    CAMERA *cam = &D_002DDF40;
    qword boundPosition = bound->qwCenter.q;
    VU_FLOAT radius(&bound->sRadius, 0);
    qword relativePosition = Subtract(boundPosition, cam->position.q);
    if (!FInsideCmFrustum(cam, relativePosition, radius)) return;
    U points[2];
    M3 basis;
    float dist;
    for (int i = 0; i < laser->numBeams;) {
        BEAM *beam = &laser->beams[i];
        Query(laser, beam, points, dist);
        if (beam->visibleLength < dist) {
            float ratio = beam->visibleLength / dist;
            points[1].q = Add(Scale(points[0].q, VU_FLOAT(1.0f - ratio)), Scale(points[1].q, VU_FLOAT(ratio)));
        }
        if (laser->lineObject) func_001A5FB8(laser->lineObject, points[0].q, points[1].q, 1.0f, 1.0f);
        qword dir;
        if (laser->stretchObject || laser->caps[0].palo || laser->caps[1].palo) {
            dir = Subtract(points[1].q, points[0].q);
            basis = BuildOrthonormalMatrixZ(dir, D_002A2DC0);
        }
        if (laser->stretchObject) {
            float length = Length(dir);
            if (0.01f < length) {
                U scale;
                scale.f[0] = length * 0.01f;
                scale.f[1] = 1.0f;
                scale.f[2] = 1.0f;
                M4 render;
                render = LoadMatrixFromPosRotScale(points[0].q, &basis, &scale);
                func_001A5EE8(laser->stretchObject, &render, 1.0f, 1.0f);
            }
        }
        int next = i + 1;
        M4 matrix;
        for (unsigned int j = 0; j < 2; j++) {
            LASENCAP *cap = &laser->caps[j];
            if (cap->palo) {
                if (cap->pscaler) {
                    U scale;
                    SCALER *scaler = cap->pscaler;
                    SCALERVTE &callback = scaler->pvt[3];
                    callback.fn((SCALER *)((char *)scaler + callback.delta), &scale, 0, cap->pasega->tLocal, cap->pasega->svt);
                    matrix = LoadMatrixFromPosRotScale(points[j].q, &basis, &scale);
                } else {
                    M4 *pm = &matrix;
                    VECTOR_opAssign(&matrix.rows[3].q, points[j].q);
                    matrix.rows[0] = basis.rows[0]; pm->rows[1] = basis.rows[1]; pm->rows[2] = basis.rows[2];
                    matrix.rows[0].bits[3] = matrix.rows[1].bits[3] = matrix.rows[2].bits[3] = 0;
                    pm->rows[3].f[3] = 1.0f;
                }
                func_001A5EE8(cap->palo, &matrix, 1.0f, 1.0f);
            }
        }
        i = next;
    }
}

