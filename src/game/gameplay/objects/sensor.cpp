// World positions of a beam's two endpoints (a fixed point from the sensor's root space, or the point on the path)
// and, when ps is given, their distance.
extern "C" void GetLasenBeamEnds(LASENV *laser, BEAMEND *ends, qword *apos, float *ps)
{
    uint i;
    BEAMEND *end = ends;
    for (i = 0; i < 2; i++, end++) {
        switch (end->kind) {
        case 0:
            apos[i] = func_0022FC48(laser->pxfRoot, 0, end->pos);
            break;
        case 1:
            EvaluateShapeS(end->track.path, &apos[i], 0, end->track.cursor);
            break;
        }
    }
    if (ps) {
        int f;
        __asm__("lqc2 $vf1, %1\n\tlqc2 $vf2, %2\n\tvsub.xyzw $vf2, $vf2, $vf1\n\tvmul.xyz $vf2, $vf2, $vf2\n\tvaddw.x $vf3, $vf0, $vf0w\n\tvadday.x $ACC, $vf2, $vf2y\n\tvmaddz.x $vf2, $vf3, $vf2z\n\tvsqrt $Q, $vf2x\n\tvwaitq\n\tvaddq.x $vf2, $vf0, $Q\n\tqmfc2.ni %0, $vf2" : "=r"(f) : "m"(apos[1]), "m"(apos[0]));
        *(int *)ps = f;
    }
}

/* AddLasenBeamXps (LASEN vt60): for every beam, find where it hits the request's object (first ClsgClipEdgeToObject,
   else the CID 0x33 test func_00205670), add a kind-10 contact there with PxpAdd, and post ZapLasenBeams through
   EnsureSwCallback. What mattered for the match:
    - the same 6-argument virtual signature as AddHackwallXps / AddBombCustomXps, with every argument passed through to
      the empty base stub func_001F5990 (no code, but the call's argument uses fix the prologue schedule);
    - VU helpers taking VU_VECTOR parameters (const qword & conversion): the extra RTL copies keep the loop above
      loop.c's ~95-insn limit, so i * sizeof(BEAM) stays a mult inside the loop as in the target;
    - Len(v) = Sqrt(Dot(v, v)) with a two-input Dot, one asm per VU step (target VU order and vf registers);
    - the distance is a float in a GPR (qmfc2) passed bit-for-bit as PxpAdd's int argument (v0 scratch, not v1). */
static inline qword Sub(VU_VECTOR a, VU_VECTOR b)
{
    qword d;
    __asm__("vsub.xyzw %0, %1, %2" : "=j"(d) : "j"(a.q), "j"(b.q));
    return d;
}
// Dot product, in lane x.
static inline qword Dot(VU_VECTOR a, VU_VECTOR b)
{
    qword d, one;
    __asm__("vmul.xyz %0, %2, %3\n\tvaddw.x %1, $vf0, $vf0w\n\tvadday.x $ACC, %0, %0y\n\tvmaddz.x %0, %1, %0z" : "=j"(d), "=j"(one) : "j"(a.q), "j"(b.q));
    return d;
}
// Square root of lane x.
static inline qword Sqrt(VU_VECTOR d)
{
    qword l;
    __asm__("vsqrt $Q, %1x\n\tvwaitq\n\tvaddq.x %0, $vf0, $Q" : "=j"(l) : "j"(d.q));
    return l;
}
// Length of a vector, in lane x.
static inline qword Len(VU_VECTOR v) { return Sqrt(Dot(v, v)); }
// Vector divided by lane x of l.
static inline qword Div(VU_VECTOR v, VU_VECTOR l)
{
    qword r;
    __asm__("vdiv $Q, $vf0w, %1x\n\tvwaitq\n\tvmulq.xyzw %0, %2, $Q" : "=j"(r) : "j"(l.q), "j"(v.q));
    return r;
}
// Lane x as a float.
static inline float Scalar(VU_VECTOR v)
{
    float f;
    __asm__("qmfc2.ni %0, %1" : "=r"(f) : "j"(v.q));
    return f;
}

// LASEN vtable slot 60: raycast each beam (0x14C6A0) and record what it hits (contact list per beam), then zap. (inferred)
extern "C" void AddLasenBeamXps(LASENV *laser, REQUEST *q, int a2, int a3, int a4, XP **ppxp)
{
    int i;
    func_001F5990(laser, q, a2, a3, a4, ppxp);
    for (i = 0; i < laser->numBeams; i++) {
        BEAM *e = &laser->beams[i];
        qword seg[2];
        U pos;
        HIT hit;
        int found = 0;
        GetLasenBeamEnds(laser, e->ends, seg, 0);
        if (!ClsgClipEdgeToObject(q, seg[0], seg[1], 1, &hit)) {
            SOV *so = *q->psub->ppso;
            if (FIsBasicDerivedFrom__FP5BASIC3CID(so, (CID)0x33))
                found = func_00205670(so, seg[0], seg[1], &pos.q);
        } else {
            found = 1;
            pos.q = hit.pos;
        }
        if (found) {
            float dist = Scalar(Len(Sub(seg[0], pos.q)));
            qword dir = Sub(seg[1], seg[0]);
            dir = Div(dir, Len(dir));
            PxpAdd(&D_003DD490, laser->apart, q, pos.q, dir, 10, *(int *)&dist, 0, &e->firstContact, 0.0f);
            EnsureSwCallback(&D_003DD490, laser, &LASENV::ZapBeams, 0);
        }
    }
}

// For each beam: length = endpoint distance; if something blocks it, the nearest contact is zapped (InflictZap kind
// 0x1000, -10) and the visible length is cut to it. (inferred)
void LASENV::ZapBeams(int)
{
    LASENV *laser = this;
    int i;
    for (i = 0; i < laser->numBeams; i++) {
        qword apos[2];
        ZAP zap;
        float s;
        BEAM *beam = &laser->beams[i];
        GetLasenBeamEnds(laser, beam->ends, apos, &s);
        if (beam->firstContact == 0) {
            beam->fullLength = beam->visibleLength = s;
        } else {
            float sMin = s;
            XP *pxpMin = 0;
            XP *pxp;
            for (pxp = beam->firstContact; pxp; pxp = pxp->nextContact) {
                if (pxp->s < sMin) {
                    sMin = pxp->s;
                    pxpMin = pxp;
                }
            }
            func_002333B4(&zap, 0, sizeof(zap));
            zap.plasen = laser;
            zap.pv4 = pxpMin->axps[0].pv0;
            zap.pv8 = pxpMin->axps[1].pvC;
            zap.grf = 0x1000;
            zap.dhp = -10;
            zap.pos = pxpMin->axps[0].qwPos;
            func_001F7598(&zap);
            beam->visibleLength = sMin;
        }
    }
}

