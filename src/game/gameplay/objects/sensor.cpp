// Advance path-driven endpoints along their segment profiles at speed(+0x1C0)*dt (fmodf wrap), mark the tree dirty,
// recompute length. (inferred)
extern "C" void MoveLasenEndpoints(LASENV *laser)
{
    int i;
    for (i = 0; i < laser->numBeams; i++) {
        BEAM *beam = &laser->beams[i];
        int f = 0;
        uint j;
        for (j = 0; j < 2; j++) {
            BEAMEND *end = &beam->ends[j];
            SEGMENT *seg;
            float t;
            if (end->kind != 1)
                continue;
            seg = &end->track.motion.segments[end->track.motion.current];
            seg->elapsed = t = seg->elapsed + laser->endpointSpeed * D_002DDED0.dt;
            if (seg->duration < t) {
                float r = fmodf(t, seg->duration);
                end->track.motion.current = (end->track.motion.current + 1) % end->track.motion.count;
                seg = &end->track.motion.segments[end->track.motion.current];
                seg->elapsed = r;
            }
            end->track.cursor = seg->start + seg->speed * seg->elapsed + seg->accel * seg->elapsed * seg->elapsed * 0.5f;
            if ((laser->ptree->grf & 2) == 0) {
                laser->ptree->grf |= 2;
                AppendDlEntry__FP2DLPv(&g_sw.dlSoTreeQueue2, laser->ptree);
            }
            f = 1;
        }
        if (f && beam->firstContact == 0) {
            qword apos[2];
            float s;
            GetLasenBeamEnds(laser, beam->ends, apos, &s);
            beam->fullLength = beam->visibleLength = s;
        }
    }
}

/* RenderLasenSelf: after RenderSoSelf and a camera test of the tree's bounding sphere (FInsideCmFrustum), each beam is
   queried for its two endpoints and length (GetLasenBeamEnds). A beam longer than its visible length is pulled back
   toward the first endpoint, then the line object, the stretched middle object and the two end caps are placed along
   it in a basis built from its direction (BuildOrthonormalMatrixZ). What mattered for the match (sched1/local-alloc/
   reload dumps):
    - the radius temporary VU_FLOAT(const float *, int) is a volatile empty asm (word load into a 128-bit GPR value);
      it is the scheduler barrier that keeps the camera/tree loads before the call arguments, which puts the camera
      address straight into $a0 and the tree pointer in $v1. This form exists to reproduce the original codegen;
    - D_002A2DC0 must NOT be const: a const global is an unchanging load that sched2 moves above the spill of `dir`;
    - `dir` is a plain qword that lives across BuildOrthonormalMatrixZ, so it is spilled. Length lists its input twice
      (as the other matched Length/Dot helpers), which decides the reload register;
    - BuildOrthonormalMatrixZ / LoadMatrixFromPosRotScale return M3 / M4 by value (hidden result pointer);
    - `matrix` is declared at beam-loop scope and the facing branch writes rows 1/2 and the corner through a pointer
      (pm), rows 0 and the w words directly: the mixed sp / s2 addressing of the original. */
struct VU_FLOAT {
    qword q;
    VU_FLOAT(float f) { __asm__("qmtc2.ni %1,%0" : "=j"(q) : "r"(f)); }
    /* barrier: loads the float's word into a 128-bit GPR value without any instruction of its own */
    VU_FLOAT(const float *laser, int) { __asm__ __volatile__("" : "=r"(q) : "0"(*(const int *)laser)); }
};
extern "C" {
int FInsideCmFrustum(CAMERA *pcm, qword pos, VU_FLOAT sRadius);
void func_001A5FB8(ALO *palo, qword posA, qword posB, float a, float b);
M3 BuildOrthonormalMatrixZ(qword dir, qword up);
M4 LoadMatrixFromPosRotScale(qword pos, const M3 *pmat, const U *pscale);
qword *VECTOR_opAssign(qword *pdst, qword src);
void func_001A5EE8(ALO *palo, const M4 *pmat, float a, float b);
}
