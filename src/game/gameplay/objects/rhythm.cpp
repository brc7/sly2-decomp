// Vector scaled by a float.
static inline qwordV VecMul(qwordV v, float g)
{
    qwordV r;
    union { qwordV q; float f[4]; } s;
    qwordV ts;
    __asm__("qmtc2.ni %1, %0" : "=j"(ts) : "r"(g));
    s.q = ts;
    __asm__("vmulx.xyzw %0, %1, %2x" : "=j"(r) : "j"(v), "j"(s.q));
    return r;
}
