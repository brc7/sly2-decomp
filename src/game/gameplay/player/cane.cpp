// Picks the cane attack state: takedown (jts 0x10) if a nearby target (within D_002BF4AC) has its takedown behaviour
// (0xB1) pointing at Sly; from a sidestep, 0xE/0x10/0x12/0x14 by heading quadrant; else 0xE, or 0xC on the ground.
extern "C" int ChooseJtAttackCaneState(JT *jt)
{
    int n;
    if (jt->interactTarget) {
        qword d, l;
        float g;
        int f;
        d = VuSub(GetLoWorldPos(jt->interactTarget), GetLoWorldPos(jt));
        __asm__("vmul.xy %0, %1, %1\n\tvaddy.x %0, %0, %0y" : "=j"(l) : "j"(d));
        __asm__("vsqrt Q, %1x\n\tvwaitq\n\tvaddq.x %0, $vf0, Q" : "=j"(l) : "j"(l));
        g = VuToFloat(l);
        f = 0;
        if (g < D_002BF4AC)
            f = IsWithinLimits__FP2LMf(D_002BF4B0, QwordZ(d)) != 0;
        if (f) {
            BHVSUBJECT *pt = (BHVSUBJECT *)FindBhvInBhvstk((char *)jt->interactTarget + 0x26C, 0xB1);
            if (pt && pt->subject == jt) {
                int k = pt->kind;
                if (k < 2) {
                    if (k >= 0) {
                        SetJtState__FP2JT3JTS4JTBS(jt, 0x10, -1);
                        return -1;
                    }
                }
            }
        }
    }
    if (jt->bodyState == 5) {
        float *pa = (float *)jt->GetWorldMatrix();
        float *pb = (float *)jt->GetWorldMatrix();
        float d = NormalizeAngle__Ff(jt->controller->leftStickAngle - atan2f(pa[1], pb[0]));
        float ad = __builtin_fabsf(d);
        if (ad < 0.7853982f)
            n = 0xE;
        else if (2.3561945f < ad)
            n = 0x10;
        else if (0.0f < d)
            n = 0x12;
        else
            n = 0x14;
    } else {
        n = 0xE;
        if (jt->state == 0)
            n = 0xC;
    }
    switch (jt->animState) {
    case 0xC: case 0xE: case 0x10: case 0x12: case 0x14:
        n++;
        break;
    case 0xD: case 0xF: case 0x11: case 0x13: case 0x15:
        break;
    default:
        if (ShouldJtSweepBack(jt))
            n++;
        break;
    }
    return n;
}

// The next sweep cane state: alternates 0x16 and 0x17, otherwise 0x17 for a back sweep (ShouldJtSweepBack) or 0x16.
extern "C" int ChooseJtSweepCaneState(JT *jt)
{
    int r;
    switch (jt->animState) {
    case 0x16: r = 0x17; break;
    case 0x17: r = 0x16; break;
    default: r = ShouldJtSweepBack(jt) ? 0x17 : 0x16; break;
    }
    return r;
}

