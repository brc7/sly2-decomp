typedef int qword __attribute__((mode(TI)));
typedef union WORD { unsigned int bits; float value; } WORD;
typedef union U { qword q; float f[4]; int i[4]; } U;
struct M4 { qword r[4]; };
struct ACTOR; struct MULTI;

/* g++ 2.95 vtable entry: this-adjust delta and the function. */
struct VT { short delta, pad; void *fn; };

/* A directional clip (only its duration, +0x74, is read). */
struct CLIP { char pad[0x74]; WORD duration; };
/* An animation segment object returned by FindAsegChannel (+4) and its vtable (slot 3 samples a position). */
struct ASEGV;
typedef struct { short delta; short pad; void (*sample)(ASEGV *, float, float, qword *, void *); } ASEGVT;
struct ASEGV { ASEGVT *vt; };
struct ASEGREF { int unknown0; ASEGV *segment; };

/* One of the eight directional axes (an array of 8, 0x20 each): blend weight, clip, root velocity. */
struct DIRAXIS
{
    union { float value; int bits; } weight;  /* +0x00 */
    CLIP *clip;                               /* +0x04 nonzero: the axis is active */
    char pad8[8];
    U direction;                              /* +0x10 root velocity of the clip */
};
typedef char assert_DIRAXIS_size[sizeof(DIRAXIS) == 0x20 ? 1 : -1];

/* The animation request (+0x40: rate, read as a float or as its bits). */
struct ANIMV { char pad[0x40]; union { float rate; int ratebits; }; };

/* The object the player faces; +0x494: its anchor. */
struct TARGETV { char pad[0x494]; TARGETV *anchor; };

/* View of the player fields used here. */
struct PLAYERV
{
    char pad0[0xC];
    VT *vt;                 /* +0x00C vtable (33 GetVelocity, 35 SetVelocity) */
    char pad10[0x180];
    U acceleration;         /* +0x190 */
    char pad1A0[8];
    float heading;          /* +0x1A8 */
    char pad1AC[0xE84];
    ANIMV *anim;            /* +0x1030 */
    int pad1034;
    int side;               /* +0x1038 -1 none, 0 negative, 1 positive */
    char pad103C[0xA0];
    TARGETV *target;        /* +0x10DC */
    int pad10E0;
    int targetMode;         /* +0x10E4 3: face the target's anchor */
};
typedef char assert_PLAYERV_side[(unsigned int)&((PLAYERV *)0)->side == 0x1038 ? 1 : -1];
typedef char assert_PLAYERV_target[(unsigned int)&((PLAYERV *)0)->targetMode == 0x10E4 ? 1 : -1];

