// Starts a flight of the given kind (jump, double jump 6, fall, wall run 0x11, rail kinds ...): resets the record
// unless double-jumping, computes the launch velocity (PlanJtLaunchVelocity), picks the directional clip and the
// landing target object, and enters the air state. The main way every other state launches the player into the air.
void SetJtAirJump(JTAIR *air, int kind, int n2, LO *lo)
{
    qword vel;
    qword velWall;
    float t;
    if (kind != 6)
        air->jumpKind = kind;
    air->unknown08 = n2;
    air->player->SetPlayerState(1);
    if (kind != 6)
    {
        air->unknown40 = 0;
        t = g_clock.time;
        air->unknown4C = t;
        air->unknown48 = t;
        air->unknown44 = t;
    }
    if (kind == 9)
    {
        air->rGravitySaved = air->player->unknown260;
        SetStepGravityRatio(air->player, D_002BF750);
    }
    vel = JtPlanLaunchVz(air, kind);
    air->player->SetVelocity(vel);
    t = g_clock.time;
    air->player->unknown131C = t;
    if (kind != 6)
        air->startTime = g_clock.time;
    switch (kind)
    {
        case 0:
            SetJtAirState(air, 4, lo);
            air->canDoubleJump = 1;
            air->unknown24 = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
        case 0xB:
            SetJtAirState(air, 4, lo);
            air->unknown24 = 1;
            air->canDoubleJump = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
        case 3:
            if (air->player->controller->leftStickDeflection < 0.2f)
            {
                qword dvel;
                air->unknown40 = 3;
                dvel = SetVectorCylind(air->player->targetHeading, D_002BF754, 0.0f);
                air->player->SetVelocity(VuAdd(vel, dvel));
            }
            SetJtAirState(air, 0, lo);
            air->canDoubleJump = 1;
            air->unknown34 = 1.0f;
            air->speedRatio = 0.6f;
            air->unknown24 = 0;
            break;
        case 1:
        case 2:
        case 0x12:
            SetJtAirState(air, 0, lo);
            air->canDoubleJump = 1;
            air->unknown24 = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
        case 9:
            SetJtAirState(air, 0, lo);
            air->unknown24 = 0;
            air->canDoubleJump = 1;
            SetPlayerTn(air->player, air->ptnLaunch);
            air->speedRatio = D_002BF758;
            air->unknown34 = D_002BF75C;
            air->isGravityChanged = 1;
            break;
        case 7:
            SetJtAirState(air, 7, lo);
            air->canDoubleJump = 1;
            air->unknown24 = 0;
            air->speedRatio = 1.0f;
            air->unknown34 = 1.0f;
            break;
        case 8:
            SetJtAirState(air, 5, lo);
            air->unknown24 = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            air->canDoubleJump = 1;
            DecomposeCylind(vel, &air->smashAngle, &air->smashDistance, 0);
            air->unknownB4 = 1.0f;
            break;
        case 6:
        {
            int state = 2;
            if (air->jumpKind < 0xF)
            {
                if (air->jumpKind > 0xC)
                    state = 3;
            }
            SetJtAirState(air, state, lo);
            break;
        }
        case 0xE:
        {
            float gRatio;
            SetJtAirState(air, 1, lo);
            gRatio = D_002BF760;
            air->canDoubleJump = 1;
            air->unknown34 = D_002BF764;
            air->unknown24 = 0;
            air->speedRatio = gRatio;
            if (air->player->controller->leftStickDeflection < 0.2f)
            {
                qword dvel;
                air->unknown40 = 3;
                dvel = SetVectorCylind(air->player->controller->leftStickAngle, D_002BF730 * gRatio, 0.0f);
                air->player->SetVelocity(VuAdd(vel, dvel));
            }
            break;
        }
        case 0xD:
            SetJtAirState(air, 1, lo);
            air->canDoubleJump = 1;
            air->speedRatio = D_002BF768;
            air->unknown34 = D_002BF76C;
            air->unknown24 = 0;
            break;
        case 0xA:
            air->unknown40 = -1;
            SetJtAirState(air, 0x15, lo);
            air->unknown24 = 0;
            air->canDoubleJump = 0;
            air->unknown34 = 0.0f;
            air->speedRatio = 0.0f;
            break;
        case 0xC:
            SetJtAirState(air, 1, lo);
            air->unknown40 = 3;
            air->canDoubleJump = 1;
            air->unknown24 = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
        case 0x10:
            SetJtAirState(air, 4, lo);
            air->unknown24 = 0;
            air->canDoubleJump = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
        case 0xF:
            SetJtAirState(air, 0, lo);
            air->unknown24 = 0;
            air->canDoubleJump = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
        case 0x11:
            if (air->state == -1)
            {
                air->player->SetVelocity(VuAdd(ProjectOutVec(velWall, D_002A2DC0), D_002BF770));
                air->canDoubleJump = 1;
            }
            SetJtAirState(air, 0x16, 0);
            air->unknown24 = 0;
            air->unknown2C = 0;
            air->unknown34 = 1.0f;
            air->speedRatio = 1.0f;
            break;
    }
    if (kind == 6)
        return;
    if (kind != 0x11)
        air->unknown2C = air->canDoubleJump;
    if (IsBasicDerivedFrom(air->player, (CID)0x35))
        ((JT *)air->player)->janim.unknown10 = -1;
    air->zStart = QwordZ(PosLoWorld(air->player));
}
