// tu_19F0A8.cpp -- world-wide player/guard broadcasts: the timed guard override (every guard forced into special
// state 0xE for D_002BF938 seconds, started by a gadget in stepplayer.cpp), setting one special state on all guards,
// and a refresh call on every player after a power-up purchase or cheat.
// Entry points: SetGuardOverride, UpdateSwGuardOverride (per frame from UpdateSw), SetAllGuardsSpecialState,
// RefreshPlayersAfterPowerupChange. TU 0x19F0A8..0x19F3E8 (6 functions, address order).
// SLY2_ALIAS: __static_initialization_and_destruction_0=StaticInit_tu_19F0A8
