// The HUD tags: the current job's name plate, then the objective of its first open task in sorted task order. (inferred)
extern "C" void GatherJtModeHudTags(JTMODEHUD *hud)
{
    WIDGET *pt = hud->pwidgetHud;
    if (!pt)
        return;
    pt->tags[0] = pt->tags[1] = -1;
    SW *pg = &D_003DD490;
    if (!pg->currentJob || ((JOB *)pg->currentJob)->labelNameId == -1)
        return;
    hud->pwidgetHud->tags[0] = ((JOB *)pg->currentJob)->labelNameId;
    int n = 1, i = 0;
    SW *pgLoop = CopyGame(pg);
    STACKSCOPE fr;
    int c;
    TASK **ap;
    SortTasksTopologically(&c, &ap);
    qsort(ap, c, 4, CompareTasks);
    for (; i < c; i++) {
        TASK *x = ap[i];
        if (pgLoop->currentJob == x->pjob && x->objectiveTextId != -1 && !IsTaskComplete(x)) {
            hud->pwidgetHud->tags[n++] = x->objectiveTextId;
            break;
        }
    }
}
