// Initializes the player's look/recon mode context (STEPPLAYER+0xF00): owner, state -1, requested kind -1, then its
// HUD. Kinds: 0 binocucom, 1 recon (runtime-verified), 2 another look mode.
extern "C" void InitJtMode(JTMODE *jtMode, STEPPLAYER *player)
{
    jtMode->player = player;
    jtMode->state = -1;
    jtMode->kind = -1;
    InitJtModeHud(&jtMode->hud, jtMode);
}

// Post-load: binds the mode HUD widgets.
extern "C" void PostLoadJtMode(JTMODE *jtMode)
{
    PostLoadJtModeHud(&jtMode->hud);
}

// Requests mode `kind`: if a mode is running and the request is recon (1), ends and resets the current one first;
// stores the kind and enters state 0 (starting). Kind 0 is the binocucom (all three characters), 1 recon.
extern "C" void StartJtMode(JTMODE *jtMode, int kind, STEP *otherStep, WIDGET *widget)
{
    if (jtMode->state != -1) {
        // A running mode only gives way to a recon request: end and reset it first.
        if (jtMode->kind == 1 || kind != 1)
            return;
        SetJtModeState(jtMode, 2);
        SetJtModeState(jtMode, -1);
    }
    jtMode->kind = kind;
    jtMode->pstepOther = otherStep;
    jtMode->ploHudOverride = widget;
    SetJtModeState(jtMode, 0);
}


// Leaves the mode (state 2, ending) unless the owner is in state 0, 8, 9 or 10.
extern "C" void EndJtMode(JTMODE *jtMode) {
    if (jtMode->hud.unknown14) {
        switch (*jtMode->hud.unknown14) {
        case 0: case 8: case 9: case 10: return;
        }
    }
    SetJtModeState(jtMode, 2);
}

// SetJtModeState: ported from Lilly's personal Sly 2 decomp (src/P2/jtmode.c), reduced to the declarations it needs.
// Every global is named by its address; the function keeps its readable name and gets the team symbol through __asm__.
// Globals: D_002DDED0 (g_clock), D_002DDF40 (g_cm), D_002A2DD0 (g_qwZero), D_003DD040 (g_sndmgr), D_003DD490 (g_sw)
// 0x0019CD38 SetJtModeState__FP6JTMODEi  (our name)
// Leaving a state: from off (-1) the mode takes hold of the hero's own animation (held at speed 0; kind 1 also counts a no-pause request in the world); from running (1) the
// camera policy is taken off the camera's list (kind 1 also lets the held object go), the camera cuts, the sound buses return to full volume and the hero
// is let go (virtual 86). Entering a state: starting (0) plays the start clip, running (1) pushes the camera policy (CPLOOK priority 7 for kinds 0 and 2, the recon
// camera priority 8 for kind 1), turns the hero to its look direction, stops him and the held object and lowers sound buses 0 and 1 to 0.6; ending (2) plays the end clip and
// off (-1) gives the hero's animation back. The overlay (hud) follows the same states.
// Mode state change: -1 off, 0 starting, 1 running (pushes the look camera policy at priority 7 for kinds 0/2 or the
// recon camera at priority 8 for kind 1, stops the hero and ducks sound buses 0/1 to 0.6), 2 ending; the HUD follows.
void SetJtModeState(JTMODE *jtMode, int state)
{
    ASEG *aseg;
    if (state == jtMode->state)
        return;
    switch (jtMode->state)
    {
        case 1:
            switch (jtMode->kind)
            {
                case 0:
                    RevokeCmPolicy(&g_cm, 0xF, 7, &g_cm.cplook, jtMode->player, 0);
                    break;
                case 1:
                    RevokeCmPolicy(&g_cm, 0xF, 8, &g_cm.cpzoom, jtMode->player, 0);
                    {
                        STEP *step = jtMode->pstepOther;
                        if (step)
                        {
                            step->RemoveDialogSmRefs(0x3F, 1);
                            SetSoCnstrForce(step, 0);
                        }
                    }
                    jtMode->player->RemoveDialogSmRefs(0x3F, 0);
                    break;
                case 2:
                    RevokeCmPolicy(&g_cm, 0xF, 7, &g_cm.cplook, jtMode->pstepOther, 0);
                    break;
            }
            CutCm(&g_cm);
            SetSndmgrChannelVolume(&D_003DD040, 0, 1.0f, 3);
            SetSndmgrChannelVolume(&D_003DD040, 1, 1.0f, 3);
            if (jtMode->kind != 2)
                jtMode->player->SetPlayable(0);
            jtMode->state = state;
            break;
        case -1:
        {
            if (jtMode->kind == 1)
            {
                IncrementSwInputLock(&D_003DD490);
                IncrementSwNoPause(&D_003DD490);
            }
            STEPPLAYER *player = jtMode->player;
            if (player->activeAnimation)
                jtMode->pasegaHold = player->activeAnimation;
            else if (player->activeStateMachine)
                jtMode->pasegaHold = player->activeStateMachine->pasegaCur;
            if (jtMode->pasegaHold)
            {
                jtMode->pasegaHold->AddRef();
                SetAsegaSpeed(jtMode->pasegaHold, 0.0f);
            }
            jtMode->state = state;
            break;
        }
        default:
            jtMode->state = state;
            break;
    }
    jtMode->enterTime = D_002DDED0.time;
    aseg = 0;
    switch (state)
    {
        case 0:
            aseg = jtMode->pasegStart;
            break;
        case 1:
            switch (jtMode->kind)
            {
                case 0:
                    SetCmPolicy(&g_cm, 7, &g_cm.cplook, (int)jtMode->player, 0);
                    SetStepRadTarget(jtMode->player, g_cm.cplook.panAngle);
                    jtMode->hud.SetState(0);
                    break;
                case 1:
                    SetCmPolicy(&g_cm, 8, &g_cm.cpzoom, (int)jtMode->player, 0);
                    SetStepRadTarget(jtMode->player, g_cm.cpzoom.panAngle);
                    {
                        STEP *step = jtMode->pstepOther;
                        if (step)
                        {
                            step->AddDialogSmRefs(0x3F, 1);
                            SetSoCnstrForce(step, 1);
                            ClearXyz(&step->unknown190);
                            step->SetVelocity(D_002A2DD0);
                            step->SetAngularVelocity(D_002A2DD0);
                        }
                    }
                    jtMode->hud.SetWidgetCur(jtMode->ploHudOverride);
                    jtMode->hud.SetState(0);
                    jtMode->player->AddDialogSmRefs(0x3F, 0);
                    break;
                case 2:
                    SetCmPolicy(&g_cm, 7, &g_cm.cplook, (int)jtMode->pstepOther, 0);
                    jtMode->hud.SetState(0);
                    break;
            }
            ClearXyz(&jtMode->player->unknown190);
            jtMode->player->SetVelocity(D_002A2DD0);
            jtMode->player->SetAngularVelocity(D_002A2DD0);
            CutCm(&g_cm);
            SetSndmgrChannelVolume(&D_003DD040, 0, 0.6f, 3);
            SetSndmgrChannelVolume(&D_003DD040, 1, 0.6f, 3);
            if (jtMode->kind != 2)
                jtMode->player->SetPlayable(1);
            break;
        case 2:
            jtMode->hud.SetState(2);
            aseg = jtMode->pasegEnd;
            break;
        case -1:
            switch (jtMode->kind)
            {
                case 0:
                case 2:
                    jtMode->hud.SetState(-1);
                    break;
                case 1:
                    jtMode->hud.SetState(-1);
                    DecrementSwInputLock(&D_003DD490);
                    DecrementSwNoPause(&D_003DD490);
                    break;
            }
            if (jtMode->pasegaHold)
            {
                SetAsegaSpeed(jtMode->pasegaHold, 1.0f);
                jtMode->pasegaHold->Release();
                jtMode->pasegaHold = 0;
            }
            jtMode->kind = -1;
            break;
    }
    if (aseg && !jtMode->player->IsFreeMoving())
        aseg = 0;
    ReplaceCurrentAseg(aseg, (ALO *)jtMode->player, 0.0f, 1.0f, 1, &jtMode->animationPlayback);
}

// Per-frame mode state machine: state 0 waits for the start clip then runs, state 1 turns the player toward the look
// direction, state 2 waits for the end clip then turns the mode off; updates the HUD.
extern "C" void UpdateJtMode(JTMODE *jtMode)
{
    int n;
    do {
        n = jtMode->state;
        switch (n) {
        case 0:
            jtMode->player->qwUnknown190 = D_002A2DD0;
            if (!jtMode->animationPlayback || IsAsegaRetracted(jtMode->animationPlayback))
                SetJtModeState(jtMode, 1);
            break;
        case 1:
            jtMode->player->qwUnknown190 = D_002A2DD0;
            switch (jtMode->kind) {
            case 0:
                SetStepTargetHeading(jtMode->player, g_cm.cplook.panAngle);
                jtMode->hud.zoom = g_cm.cplook.zoom;
                UpdateJtModeHud(&jtMode->hud);
                break;
            case 1:
                SetStepTargetHeading(jtMode->player, g_cm.cpzoom.panAngle);
                jtMode->hud.zoom = g_cm.cpzoom.zoom;
                UpdateJtModeHud(&jtMode->hud);
                break;
            }
            break;
        case 2:
            jtMode->player->qwUnknown190 = D_002A2DD0;
            if (!jtMode->animationPlayback || IsAsegaRetracted(jtMode->animationPlayback))
                SetJtModeState(jtMode, -1);
            break;
        }
    } while (n != jtMode->state);
    if (jtMode->kind != 0)
        return;
    POCTL *v = jtMode->player->controller;
    if (v->state != 1)
        return;
    v->dxLeft = v->dyLeft = v->leftStickAngle = v->leftStickDeflection = 0.0f;
    v->dyRight = v->rightStickAngle = v->rightStickDeflection = 0.0f;
    v->dxRight = 0.0f;
}

// Initializes the mode HUD record: owner, state -1; for Sly (CID 0x35) also binds the recon selector at JT+0x1D40.
extern "C" void InitJtModeHud(JTMODEHUD *hud, JTMODE *jtMode)
{
    hud->pjtmode = jtMode;
    hud->state = -1;
    if (IsBasicDerivedFrom__FP5BASIC3CID(jtMode->player, 0x35) != 0) {
        int *psel = (int *)((char *)hud->pjtmode->player + 0x1D40);        /* the recon selector */
        hud->unknown14 = psel;
        InitReconSel(psel, jtMode);
        return;
    }
    hud->unknown14 = 0;
}

// Finds the per-character HUD widgets by oid (Sly 0x35F/0x368, Bentley 0x360/0x369, Murray 0x361/...).
