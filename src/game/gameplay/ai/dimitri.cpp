// 0x155450: DIMITRI vtable slot 15 (PostLoad): STEPGUARD post-load, then resolves the four oids of each route
// record.
void DIMITRI::PostLoad()
{
    DIMITRI *dimitri = this;
    int i;
    PostStepguardLoad(dimitri);
    for (i = 0; i < dimitri->routeCount; i++) {
        DIMITRIROUTE *route = &dimitri->routes[i];
        route->first = (LO *)FindSwObject__FP2SWi3OIDP2LO(&g_sw, 4, route->oidFirst, dimitri);
        route->firstVolume = (VOL *)FindSwObject__FP2SWi3OIDP2LO(&g_sw, 4, route->oidFirstVolume, dimitri);
        route->second = (LO *)FindSwObject__FP2SWi3OIDP2LO(&g_sw, 4, route->oidSecond, dimitri);
        route->secondVolume = (VOL *)FindSwObject__FP2SWi3OIDP2LO(&g_sw, 4, route->oidSecondVolume, dimitri);
    }
}

