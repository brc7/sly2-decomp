// VU0 helper: distance between two points.
static __inline__ float GDist(qword a, qword b)
{
    qword d;
    float g;
    d = VuSub(a, b);
    d = VuDot(d, d);
    __asm__("vsqrt Q, %0x\n"
        "vwaitq\n"
        "vaddq.x %0, $vf0, Q" : "+j"(d));
    g = VuToFloat(d);
    return g;
}
