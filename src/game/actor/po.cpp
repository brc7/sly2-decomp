// Slot 7 (Init): InitSo, enables collection in the PO's pickup info (pzi) with itself as collector, and sets
// flag 2 in the LO flags.
extern "C" void InitPo(POV *po)
{
    int flags;
    InitSo(po);
    po->collectEnabled = 1;
    po->collector = po;
    flags = po->loFlags;
    if ((flags ^ 1) & 1) *(int *)flags |= 2; else po->loFlags = flags | 2;
}

