// Slot 7 (Init): InitSo, enables collection in the PO's pickup info (pzi) with itself as collector, and sets
// flag 2 in the LO flags.
extern "C" void InitPo(PO *po)
{
    int flags;
    InitSo(po);
    po->unknown15C = 1;
    po->unknown168 = po;
    flags = po->unknown40;
    if ((flags ^ 1) & 1) *(int *)flags |= 2; else po->unknown40 = flags | 2;
}

