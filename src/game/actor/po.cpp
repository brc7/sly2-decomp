// Forgets the presses of the buttons in grf (their press time becomes -FLT_MAX).
void ClearPoctlJoyPressed(POCTL *poctl, int buttons)
{
    float *pg;
    if (!buttons) return;
    pg = poctl->pressTimes;
    do { if (buttons & 1) *pg = -3.40282346638528859812e+38f; buttons >>= 1; pg++; } while (buttons);
}

// Rotate a direction into a matrix frame, take the perpendicular (-y, z, 0) and normalize it (fallback D_002A2DB0).
// VF hard-register pins in Norm reproduce the original VF numbering.
union U { qword q; float f[4]; };
struct M3 { qword row[3]; };
// Rotate v by the transpose of the 3x3 matrix m (into its local frame).
static inline qword Local(const M3 *m, qword v)
{
    qword q, one, a, b, c;
    q = m->row[0];
    __asm__("vmul.xyzw %2,%0,%7\n\tvmaxw.xyzw %1,$vf0,$vf0w\n\tvmul.xyzw %3,%5,%7\n\tvmul.xyzw %4,%6,%7\n\tvadday.x $ACC,%2,%2y\n\tvmaddz.x %0,%1,%2z\n\tvaddax.y $ACC,%3,%3x\n\tvmaddz.y %0,%1,%3z\n\tvaddax.z $ACC,%4,%4x\n\tvmaddy.z %0,%1,%4y"
            : "+j"(q), "=&j"(one), "=&j"(a), "=&j"(b), "=&j"(c) : "j"(m->row[1]), "j"(m->row[2]), "j"(v));
    return q;
}
// Unit vector along v, or fallback when its length is too small.
static inline qword Norm(qword v, qword fallback)
{
    register qword d __asm__("vf1"); register qword one __asm__("vf2"); qword r; float f;
    __asm__("vmul.xyz %0,%2,%2\n\tvaddw.x %1,$vf0,$vf0w\n\tvadday.x $ACC,%0,%0y\n\tvmaddz.x %0,%1,%0z" : "=j"(d), "=&j"(one) : "j"(v));
    __asm__("vsqrt $Q,%0x\n\tvwaitq\n\tvaddq.x %0,$vf0,$Q" : "+j"(d));
    __asm__("qmfc2.ni %0,%1" : "=r"(f) : "j"(d));
    if (f < 0.0001f) d = fallback;
    else __asm__("vdiv $Q,$vf0w,%0x\n\tvwaitq\n\tvmulq.xyzw %0,%1,$Q" : "+j"(d) : "j"(v));
    __asm__("qmfc2.ni %0,%1" : "=r"(r) : "j"(d));
    return r;
}
// Returns a unit lateral direction for the controller: the input direction taken into the camera pan/tilt frame,
// reduced to (-y, z, 0) and normalised, with a fixed fallback when degenerate (inferred).
extern "C" qword GetPoctlLateralVector(POCTL *poctl, qword dir)
{
    U v;
    v.q = Local((M3 *)&poctl->matPanTilt, dir);
    v.f[0] = -v.f[1];
    v.f[1] = v.f[2];
    v.f[2] = 0.0f;
    return Norm(v.q, D_002A2DB0);
}

