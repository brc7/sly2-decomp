{
    if (world->numFollowersU < 4) {
        EMB *pv;
        world->followers[world->numFollowersU++] = follower;
        pv = PemitbEnsureEmitter(follower, 1);
        if (!pv->pn) {
            MSG msg;
            msg.cb = 0x14;
            msg.nKind = 0x10;
            pv->pn = (int *)AllocClearedFromWorldHeap(&msg);
        }
    }
}

