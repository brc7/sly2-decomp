// The game record's event handler: world teardown (1) saves widget state, reset (3) applies the pending save data and
// reloads the slots, load (4) restores the tasks, 5 re-resolves the current job, task and pending task from the saved
// oids.
extern "C" void HandleGameEvent(GAME *game, int action)
{
    switch (action) {
    case 1: {   /* world teardown: in the hub level, each step player keeps its booty widget */
        if (Same((CHECK *)&g_sw.transition.destinationLevel, &D_002A37E8)) {
            P *players[3];
            int found = FindSwObjectsByClass(&g_sw, 5, 0x34, 0, 3, players);
            if (found > 0) {
                P **cursor = players;
                int count = found;
                do {
                    P *player = *cursor;
                    if (player->widget)
                        (void)ClearStepplayerBootySave(player, GetCurrentBootyEntryId(player->widget));
                    --count;
                    ++cursor;
                } while (count);
            }
        }
        break;
    }
    case 3: {   /* reset: a new game, or the save data loaded from a slot */
        if (g_sw.transition.flags & 1) {
            InitGame(game);
            g_save.currentSlot = 0;
        } else if (g_sw.transition.flags & 0x40)
            ApplyPendingSaveData();
        ReloadSaveSlots(&g_save);
        if (GetCurrentWorld())
            break;
        if (g_save.nState != 6 || g_save.currentSlot || !g_save.newestSlot)
            break;
        if (GetFloat(g_sw.psvpDt, &g_gs) != 0.0f)
            break;
        if (GetFloat(g_sw.psvpDt, g_save.newestSlot) != 0.0f)
            ApplyGsSettings(g_save.newestSlot);
        break;
    }
    case 4:
        RestoreTasksAfterLoad(game);
        break;
    case 5: {   /* re-resolve the saved current job / task / pending task */
        int i = 0;
        LEASE mark;
        int count;
        TASK **tasks;
        SortTasksTopologically(&count, &tasks);
        for (; i < count; i++) {
            TASK *task = tasks[i];
            StateSourceScope restoring(task, STATE_SOURCE_RESTORE, 0);
            RestoreTaskState(task);
        }
        SW *world = &g_sw;
        SetSwJobCur(world, FindSwObject__FP2SWi3OIDP2LO(world, 0x105, game->oidJobCur, 0));
        SetSwTaskCur(world, FindSwObject__FP2SWi3OIDP2LO(world, 0x105, game->oidTaskCur, 0));
        SetSwTaskPending(world, FindSwObject__FP2SWi3OIDP2LO(world, 0x105, game->oidTaskPending, 0));
        if (world->currentJob)
            BeginJob((JOB *)world->currentJob);
        if (world->currentTask)
            BeginTask((TASK *)world->currentTask);
        if (world->transition.flags & 4) {
            if (world->pendingTask)
                AnnounceTaskJob((TASK *)world->pendingTask);
            else if (world->currentJob)
                AnnounceTaskJob(((JOB *)world->currentJob)->firstTask);
        }
        for (int j = 0; j < count; j++) {
            TASK *task = tasks[j];
            StateSourceScope gameplay(task, STATE_SOURCE_GAMEPLAY, 0);
            UpdateTaskSaveVars(task);
        }
        mark.Release();
        break;
    }
    case 16: {   /* no job: back to the return warp */
        SW *world = &g_sw;
        if (!world->currentJob)
            WipeToWorldWarp(world, 0, world->returnWarpOid, world->returnWarpContext, world->unknown3E38 ? 0x20 : 0, 0x30A);
        break;
    }
    case 2: case 6: case 7: case 8: case 9: case 10: case 11: case 12: case 13: case 14: case 15:
        break;
    }
}
