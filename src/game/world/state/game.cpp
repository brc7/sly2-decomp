// Per-tick timers: adds dt to the total play time and the current episode's play time (save variables), to the current
// job's elapsed time, and eases the difficulty when the job takes long.
extern "C" void UpdateGameTimers()
{
    if (!g_sw.psvpDt)
        return;
    float playTime = GetFloat(((OPT *)g_sw.psvpDt), &g_gs);
    SetPlayTimeFloat(((OPT *)g_sw.psvpDt), playTime + g_clock.deltaTime, &g_gs);
    unsigned int episode = GetCurrentWorld();
    if (episode < 9) {
        OPT *var = ((OPT **)g_sw.apsvpEpisodeDt)[episode];
        if (var) {
            float episodeTime = GetFloat(var, &g_gs);
            SetFloat(var, episodeTime + g_clock.deltaTime, &g_gs);
        }
    }
    JOB *job = (JOB *)g_sw.currentJob;
    if (job && (float)g_joy.dtIdle < 10.0f) {   /* only while the player is not idle */
        job->elapsedTime += g_clock.deltaTime;
        if (job->easeStartTime < job->elapsedTime)
            ChangeDifficulty(D_002DE578, g_clock.deltaTime / (job->easeEndTime - job->easeStartTime));
    }
}

