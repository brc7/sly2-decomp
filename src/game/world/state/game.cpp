// Applies one state rsmg record matching the new state: finds the state machine and seeks or sets the goal (default
// goals 0x612..0x615 for states 0..3).
extern "C" void TriggerStateRsmg(void *pvUnused, STATERSMG *record, int newState, int source)
{
    void *root;
    void *sma;
    int goal;
    if (record->nState != -1 && record->nState != newState) return;
    if (record->fRestoreOnly && source == STATE_SOURCE_GAMEPLAY) return;
    if (record->level != -1 && record->level != GetCurrentLevelIndex__Fv()) return;
    if (FindSwObjects(&g_sw, 0x205, record->oidRoot, 0, 1, &root) != 1) return;
    if (!IsBasicDerivedFrom__FP5BASIC3CID(root, 0x30)) return;
    sma = FindLiveSma(root, record->oidSm);
    if (!sma) return;
    goal = record->oidGoal;
    if (record->nState == -1) {
        switch (newState) {
        case TASK_STATE_LOCKED: goal = 0x612; break;
        case TASK_STATE_AVAILABLE: goal = 0x613; break;
        case TASK_STATE_DONE: goal = 0x614; break;
        case TASK_STATE_COMPLETE: goal = 0x615; break;
        }
    }
    if (goal != -1) {
        if (source == STATE_SOURCE_RESTORE || source == STATE_SOURCE_SCRIPT)
            SeekSma(sma, goal);
        else
            SetSmaGoal(sma, goal);
    }
}
