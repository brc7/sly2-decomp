// Same idiom as sly2/util.h MinInt; kept local because the shared helper changes GetEpisodePercentComplete (8/78 instructions off).
static inline int MinIntLocal(int a, int b) { return a > b ? b : a; }
// Episode completion percentage: completed tasks (state 3) over all tasks that have successors, clamped to 1..99
// unless none or all are complete.
extern "C" int GetEpisodePercentComplete()
{
    int numCounted = 0;
    int numComplete = 0;
    STACKSCOPE fr;
    ALLOCREQ req;
    SW *pg = &D_003DD490;
    TASK **tasks = (TASK **)PvAllocReq(&req, pg->ctask * 4, 0x10);
    int numFound = FindSwObjectsByClass(pg, 5, 0x85, 0, pg->ctask, (void **)tasks);
    for (int i = 0; i < numFound; i++) {
        TASK *task = tasks[i];
        if (task->cptaskSucc) {
            numCounted++;
            if (task->nState == TASK_STATE_COMPLETE)
                numComplete++;
        }
    }
    if (!numComplete)
        return 0;
    if (numComplete == numCounted)
        return 100;
    int maxPercent = 99;
    int percent = numComplete * 100 / numCounted;
    int result = 1;
    if (percent > 0)
        result = MinIntLocal(percent, maxPercent);
    return result;
}
