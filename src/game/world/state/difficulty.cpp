        break;
    case 34:
        Set(pdifficulty->pkey8, Get(pdifficulty->pkeyC));
        Set(pdifficulty->pkeyC, Get(pdifficulty->pkey10));
        SetG(pdifficulty->pkey10, *ptask->pgA8);
