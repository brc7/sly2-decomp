// Returns the address of a save variable in a save blob (blob + offset + index * size of its kind).
extern "C" void *GetSaveVarAddress(SVSTORE *schema, SVKEY *key, SVSET *saveSet)
{
    SVFIND find;
    FindSaveVar(schema, key, &find);
    return (char *)saveSet + (find.pent->ib + find.i * D_002C2D90[find.pent->kind]);
}

struct LMV { int a[2]; };
struct SMPV { int a[3]; };

/** @sly2-annot addr=0x1D7ED8
 * Purpose: Read a save var as a Splice CRef: switch on kind (int/float/bool or bitfield/vector/qw/v2/v3...)
 * Info: proposed name GetSaveVar (T1); TU save
 * Confidence: mid (draft) [T1 0.75] - evidence: static analysis; sources: r6_1D5150
 * See: docs/engine/save-memcard.md#5-key-functions,
 *   docs/reference/functions/save-memcard.md#save-0x1d7b88-0x1d93d8
 * @end-sly2-annot */
// Reads a save variable as a Splice value, by kind (int, float, bool or packed bit, vectors...).
CRef GetSaveVar(SVSTORE *schema, SVKEY *key, SVSET *saveSet)
{
    CRef ref;
    SVFIND find;
    SVENT *pent;
    if (!FindSaveVar(schema, key, &find) || (pent = find.pent)->kind == -1)
        return ref;
    {
        unsigned char *pv = (unsigned char *)saveSet + pent->ib;
        switch (pent->kind)
        {
        case 0:
        case 1:
        case 2:
        case 10:
            ref.SetS32(((int *)pv)[find.i]);
            break;
        case 3:
            ref.SetF32(((float *)pv)[find.i]);
            break;
        case 4:
            if (pent->fIndexed)
            {
                int i = find.i;
                unsigned char b;
                pv += i / 8;
                b = 1 << (i % 8);
                CRef_SetBool(&ref, (bool)((*pv & b) != 0));
            }
            else
            {
                CRef_SetBool(&ref, *(bool *)pv);
            }
            break;
        case 5:
            CRef_SetVector(&ref, &((qword *)pv)[find.i]);
            break;
        case 6:
            CRef_SetClq(&ref, &((qword *)pv)[find.i]);
            break;
        case 7:
            CRef_SetLm(&ref, &((LMV *)pv)[find.i]);
            break;
        case 8:
            CRef_SetSmp(&ref, &((SMPV *)pv)[find.i]);
            break;
        case 9:
            ref.SetS32(((int *)pv)[find.i]);
            break;
        }
    }
    return ref;
}

/** @sly2-annot addr=0x1D80C8
 * Purpose: Write a CRef into a save var by kind (bitfield set/clear for packed bools)
 * Info: proposed name SetSaveVar (T1); TU save
 * Confidence: mid (draft) [T1 0.75] - evidence: static analysis; sources: r6_1D5150
 * See: docs/engine/save-memcard.md#5-key-functions,
 *   docs/reference/functions/save-memcard.md#save-0x1d7b88-0x1d93d8,
 *   docs/reference/functions/splice-scripting.md#bif-0x11f440-0x1258f0
 * @end-sly2-annot */
// Writes a Splice value into a save variable, by kind (packed bools set or clear their bit).
CRef SetSaveVar(SVSTORE *schema, SVKEY *key, const CRef &refVal, SVSET *saveSet)
{
    CRef ref(0x24);
    SVFIND find;
    SVENT *pent;
    if (!FindSaveVar(schema, key, &find) || (pent = find.pent)->kind == -1)
        return ref;
    {
        unsigned char *pv = (unsigned char *)saveSet + pent->ib;
        switch (pent->kind)
        {
        case 0:
        case 1:
        case 2:
        case 9:
        case 10:
            ((int *)pv)[find.i] = refVal.u.n;
            break;
        case 3:
            ((float *)pv)[find.i] = refVal.u.g;
            break;
        case 4:
            if (pent->fIndexed)
            {
                int i = find.i;
                unsigned char b;
                pv += i / 8;
                b = 1 << (i % 8);
                if (refVal.u.n)
                    *pv |= b;
                else
                    *pv &= ~b;
            }
            else
            {
                *(int *)pv = refVal.u.n;
            }
            break;
        case 5:
        case 6:
            ((qword *)pv)[find.i] = *(qword *)refVal.u.pv;
            break;
        case 7:
            ((LMV *)pv)[find.i] = *(LMV *)refVal.u.pv;
            break;
        case 8:
            ((SMPV *)pv)[find.i] = *(SMPV *)refVal.u.pv;
            break;
        }
    }
    return ref;
}

