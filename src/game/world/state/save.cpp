extern "C" void AddSaveSymbol(SVSYMTAB *psymtab, char *pchz, int symid)
{
    unsigned int hash = UHashPchzCi(pchz);
    unsigned int ihash = hash % 0x35;
    SVSYM *psym = &psymtab->asym[psymtab->csym - 1];
    psymtab->csym--;
    psym->pchz = pchz;
    psym->symid = symid;
    psym->hash = hash;
    psym->psymNext = psymtab->apsym[ihash];
    psymtab->apsym[ihash] = psym;
}

/** @sly2-annot addr=0x1D8720
 * Purpose: Lookup name -> symbol id in 53-bucket hash (strcmp-ish 0x2342D0), -1 if absent
 * Info: proposed name NFindSaveSymbol (T1); TU save
 * Confidence: mid (draft) [T1 0.75] - evidence: static analysis; sources: r6_1D5150
 * See: docs/engine/save-memcard.md#5-key-functions,
 *   docs/reference/functions/save-memcard.md#save-0x1d7b88-0x1d93d8
 * @end-sly2-annot */
// Returns the symbol id of a name in the save symbol table, or -1.
extern "C" int NFindSaveSymbol(SVSYMTAB *psymtab, const char *pchz)
{
    unsigned int hash = UHashPchzCi(pchz);
    SVSYM *psym;
    for (psym = psymtab->apsym[hash % 0x35]; psym; psym = psym->psymNext)
    {
        if (psym->hash == hash && strcasecmp(psym->pchz, pchz) == 0)
            return psym->symid;
    }
    return -1;
}

/** @sly2-annot addr=0x1D87C0
 * Purpose: Turn a NULL-terminated varargs list of strings into a key (short array of symbol ids; non-symbols
 *   via atoi as array indices)
 * Info: proposed name BuildSaveKeyV (T1); TU save
 * Confidence: mid (draft) [T1 0.70] - evidence: static analysis; sources: r6_1D5150
 * See: docs/engine/save-memcard.md#5-key-functions,
 *   docs/reference/functions/save-memcard.md#save-0x1d7b88-0x1d93d8
 * @end-sly2-annot */
// Turns a null-terminated list of strings into a key: symbol names become their ids, numbers become array indices.
extern "C" void BuildSaveKeyV(const char *pchz, VA_LIST ap, SVKEY *pkey)
{
    VA_LIST apSave = ap;
    const char *pchzT;
    int i;
    pkey->c = 0;
    pkey->ash = 0;
    for (pchzT = pchz; pchzT; pchzT = VA_ARG_PCH(ap))
        pkey->c++;
    if (pkey->c)
    {
        MEMREQ memreq;
        memreq.cb = pkey->c * 2;
        memreq.cbAlign = 0x10;
        pkey->ash = (short *)PvAllocSlot__FP8ALLOCREQ(&memreq);
        ap = apSave;
        for (pchzT = pchz, i = 0; pchzT; pchzT = VA_ARG_PCH(ap), i++)
        {
            int symid = NFindSymbol((SVSTORE *)&g_sw.savevars, pchzT);
            if (symid == -1)
                pkey->ash[i] = atoi(pchzT);
            else
                pkey->ash[i] = symid;
        }
    }
}

