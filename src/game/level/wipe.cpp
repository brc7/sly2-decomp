extern "C" WIPE *InitWipe(WIPE *pwipe)
{
    pwipe->pwidget = 0;
    pwipe->k = -1;
    pwipe->oidWidget = -1;
    SetWipeWipes(pwipe, 0);
    return pwipe;
}

/** @sly2-annot addr=0x22B090
 * Purpose: state change with memset of transition data and checkpoint restore (RestoreChkmgrFromCheckpoint)
 * Info: proposed name SetWipeWipes (T1); TU wipe
 * Confidence: mid (draft) [T1 0.50] - evidence: static analysis; sources: r8_21BB88
 * See: docs/reference/functions/world-sw.md#wipe-0x22b040-0x22b720
 * @end-sly2-annot */
extern "C" void SetWipeWipes(WIPE *pwipe, int k)
{
    WIDGETV *pwidget;
    if (pwipe->k == k) return;
    pwipe->k = k;
    switch (k) {
    case 0:
        pwipe->fTrans = 0;
        func_002333B4(&pwipe->trans, 0, 0x4C);
        pwidget = pwipe->pwidget;
        if (pwidget) pwidget->vt[50].pfn((char *)pwidget + pwidget->vt[50].d);
        break;
    case 1:
        pwipe->pwidget->vt[49].pfn((char *)pwipe->pwidget + pwipe->pwidget->vt[49].d, 0x311);
        break;
    case 2:
        pwipe->pwidget->vt[49].pfn((char *)pwipe->pwidget + pwipe->pwidget->vt[49].d, 0x30F);
        break;
    case 3:
        SetSwTransition(&D_003DD490, &pwipe->trans);
        pwipe->fTrans = 0;
        func_002333B4(&pwipe->trans, 0, 0x4C);
        break;
    }
}

/** @sly2-annot addr=0x22B198
 * Purpose: advances wipe state machine (1->3, 2->0 when sprite done)
 * Info: proposed name UpdateWipe (T1); TU wipe
 * Notes: runtime5b: WIPE k 0..3 state machine observed (S56)
 * Confidence: mid (draft) [T1 0.55] - evidence: runtime (save-state RAM); sources: r8_21BB88+runtime
 * See: docs/reference/functions/world-sw.md#wipe-0x22b040-0x22b720
 * @end-sly2-annot */
extern "C" void UpdateWipe(WIPE *pwipe)
{
    int k = pwipe->k;
    switch (k) {
    case 0: break;
    case 1: if (!FWidgetAnimPlaying(pwipe->pwidget, 0x314)) k = 3; break;
    case 2: if (!FWidgetAnimPlaying(pwipe->pwidget, 0x314)) k = 0; break;
    }
    SetWipeWipes(pwipe, k);
}

/** @sly2-annot addr=0x22B220
 * Purpose: starts a transition to a level/warp, comparing checkpoints
 * Info: proposed name ActivateWipe (T2); TU wipe
 * Confidence: low (draft) [T2 0.40] - evidence: static analysis; sources: r8_21BB88
 * See: docs/reference/functions/world-sw.md#wipe-0x22b040-0x22b720
 * @end-sly2-annot */
extern "C" void func_0022B220(WIPE *pwipe, TRANS *ptrans, int oid, int k)
{
    switch (pwipe->k) {
    case 0:
        break;
    case 1:
        return;
    case 2:
        SetWipeWipes(pwipe, 0);
        break;
    case 3:
        return;
    }
    if (FSameFilerec(&D_003DD490.filerecCur, &ptrans->filerec))
        ptrans->grf |= 2;
    else
        ptrans->grf &= ~2;
    pwipe->pwidget = (WIDGETV *)PloFindSwObject(&D_003DD490, 0x405, (OID)oid, 0);
    if (!pwipe->pwidget) {
        SetSwTransition(&D_003DD490, ptrans);
        return;
    }
    pwipe->fTrans = 1;
    pwipe->trans = *ptrans;
    pwipe->oidWidget = oid;
    SetWipeWipes(pwipe, k);
}

