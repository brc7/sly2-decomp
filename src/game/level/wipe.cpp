static inline int IsSameFileRecord(FILEREC *first, FILEREC *second)
{
    if (first == second) return 1;
    if (!first || !second) return 0;
    return (first->aw[2] ^ first->aw[14]) == (second->aw[2] ^ second->aw[14]);
}

