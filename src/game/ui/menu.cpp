// Opens the pause menu when allowed (no transition, no dialog): builds the root page from the seven items that are
// available and pushes it. Returns whether it opened.
extern "C" int TryOpenPauseMenu(ITEM *item)
{
    char *pl;
    ITEM *psrc, *pdst;
    unsigned int i;
    int f, k;
    if (!D_003D9ED0.pool) return 0;
    if (IsSwTransitionBusy(&D_003DD490)) return 0;
    if (IsScreenShown(&D_002E6550)) return 0;
    pl = GetHeroPo(&D_003DD490);
    if (pl && IsBasicDerivedFrom__FP5BASIC3CID(pl, 0x34)) SetJtModeState__FP6JTMODEi(pl + 0xF00, -1);
    if (!AreWidgetLoadsIdle()) return 0;
    psrc = D_002C00E8;
    pdst = D_002F65D0;
    for (i = 0; i < 7; i++) {
        f = 1;
        switch (psrc->kind) {
        case 0x6A:
            f = 0;
            if (D_003DA3C0.unknown24) {
                if (GetCurrentWorld()) f = 1;
            }
            break;
        case 0x6B:
            f = 0;
            if (D_003DD490.currentJob) {
                if (GetCurrentWorld()) f = 1;
            }
            break;
        case 0x43:
            f = 0;
            if (pl) {
                k = GetBasicCid(pl);
                if (k < 0x38) {
                    if (k >= 0x35) f = 1;
                }
            }
            break;
        case 0x2C:
            break;
        case 0x42:
            f = GetCurrentWorld() != 0;
            break;
        }
        if (f) {
            *pdst = *psrc;
            pdst++;
        }
        psrc++;
    }
    PushPauseMenuPage(&D_003D9ED0, pdst - D_002F65D0, D_002F65D0, D_003D9ED0.pool, &D_002BFD38);
    if (item) item->flags |= 2;
    return 1;
}

